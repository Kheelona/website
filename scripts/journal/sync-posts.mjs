#!/usr/bin/env node
// The journal sync (task 8b.2b; ADR-014; journal-pipeline §2, §8.2, §9, §10).
//
//   node scripts/journal/sync-posts.mjs                  prebuild step 15: sync or check, by the mode below
//   node scripts/journal/sync-posts.mjs --check          by hand: compare the API with the committed file, never write
//   node scripts/journal/sync-posts.mjs --split <dir>    by hand: one <slug>.json per post of the committed file
//   node scripts/journal/sync-posts.mjs --pages          postbuild step 20: every post became a prerendered page
//   any of them with --root <dir>                        the tests point it at a fixture tree
//
// Writers draft in the admin dashboard (admin.kheelona.com → Blog), an admin publishes, and publishing triggers a
// Vercel deploy whose build runs this before `next build`. The build reads the committed snapshot,
// src/content/en-IN/stories/posts.generated.json; this script refreshes it from the API only when the mode says so:
//
//   BLOG_SYNC=off     the committed snapshot (no network), always
//   BLOG_SYNC=on      the API, on any build (by hand: refresh the committed file, then `npm run verify`, commit)
//   otherwise         the API only on a production build (resolveSiteEnv) with JOURNAL_SOURCE "api"
//                     (src/config/journal.ts; "snapshot" until the 20 guides are imported after Gate B)
//
// So verify, dev, e2e, beta and every build before the flip make no request; they check the committed file instead,
// held to the same build rules. From the API it ports main's sync (main:tools/blog/sync.mjs): 3 tries of 20 s with
// waits of 2, 4 and 6 s, `data.posts`, the shrink rule and the data compare (Postgres jsonb reorders keys, so the
// file is rewritten only when the data changed). It writes the posts sorted by slug with every key in the contract's
// order, so the committed file diffs cleanly. BLOG_API_URL overrides the API; BLOG_ALLOW_SHRINK=1 accepts a large
// drop for one build (main's names, kept).
//
// IT FAILS THE BUILD rather than ship a wrong journal (journal-pipeline §2.3): an unreachable API, an answer with no
// list of posts, a post that breaks a build rule (src/lib/journal/validate.ts: structure, tokens, links, uploads,
// videos, the topic, banned claims and retired offer terms), fewer than 4 posts, or a drop below half the last count.
// Vercel then keeps the last good deployment. Editorial faults print as warnings and the build goes on; `npm run
// verify` fails on them at the next refresh. For an urgent code deploy during an API outage the founder sets
// BLOG_SYNC=off in Vercel for one deploy (lessons §1: a variable applies to deployments created after it changes).
//
// Imports .ts files with Node's type stripping, so the steps spawn it with --disable-warning=MODULE_TYPELESS_PACKAGE_JSON
// (as prebuild/30-placeholders.mjs does). test/journal-sync.test.ts proves it, with no request.

import { existsSync, mkdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveSiteEnv } from "../../src/config/env.ts";
import { JOURNAL_API, JOURNAL_IMAGES, JOURNAL_POSTS_PATH, JOURNAL_SNAPSHOT, JOURNAL_SOURCE } from "../../src/config/journal.ts";
import { topics } from "../../src/content/en-IN/stories/topics.ts";
import {
  canonical,
  countProblem,
  diffPosts,
  editorialWarnings,
  normalisePosts,
  serialiseSnapshot,
  shrinkProblem,
  snapshotProblems,
  validatePosts,
} from "../../src/lib/journal/validate.ts";
import { findBanned } from "../../test/guards/banned-phrases.data.ts";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Main's fetch (main:tools/blog/sync.mjs:38-55): three tries, 20 s each, a 2, 4 and 6 s wait after each failure. */
export const TRIES = 3;
export const TIMEOUT_MS = 20_000;
export const BACKOFF_MS = [2_000, 4_000, 6_000];

/** The registry that reads the snapshot (task 8b.2e writes it). Until it exists the journal is the article modules,
 *  so a missing snapshot is expected; once it exists, a missing snapshot is an error. */
export const REGISTRY = "src/content/en-IN/stories/journal.ts";

/** What the gate needs from the rest of the repo (src/lib/journal/validate.ts imports nothing). */
export const RULES = Object.freeze({ themes: topics.map((t) => t.title), imagesBase: JOURNAL_IMAGES, findBanned });

const PAGES_DIR = join(".next", "server", "app", "stories");
const ROUTES_MANIFEST = join(".next", "routes-manifest.json");
const USAGE = "usage: node scripts/journal/sync-posts.mjs [--check | --split <dir> | --pages] [--root <dir>]";

/** The note the sync writes at the top of the snapshot; no timestamp, so an unchanged journal never rewrites it. */
export function syncNote(api) {
  return (
    `GENERATED by scripts/journal/sync-posts.mjs from ${api}${JOURNAL_POSTS_PATH}; do not edit. ` +
    "Refresh: BLOG_SYNC=on node scripts/journal/sync-posts.mjs"
  );
}

/**
 * Where this build's journal comes from (journal-pipeline §2.1), in order: BLOG_SYNC=off, the snapshot; BLOG_SYNC=on,
 * the API; otherwise the API only on a production build with JOURNAL_SOURCE "api". An unknown BLOG_SYNC is refused.
 * @param {Record<string, string | undefined>} env
 * @param {"snapshot" | "api"} [source]
 * @returns {{ mode: "snapshot" | "api", why: string }}
 */
export function resolveMode(env, source = JOURNAL_SOURCE) {
  const flag = env.BLOG_SYNC ?? "";
  if (flag === "off") return { mode: "snapshot", why: "BLOG_SYNC=off" };
  if (flag === "on") return { mode: "api", why: "BLOG_SYNC=on" };
  if (flag !== "") throw new Error(`BLOG_SYNC is "${flag}": use "on" or "off", or leave it unset`);
  const siteEnv = resolveSiteEnv(env);
  if (siteEnv !== "production") return { mode: "snapshot", why: `a ${siteEnv} build: only production reads the API` };
  if (source === "api") return { mode: "api", why: 'a production build with JOURNAL_SOURCE "api"' };
  return {
    mode: "snapshot",
    why: 'a production build with JOURNAL_SOURCE "snapshot" (until the 20 guides are imported after Gate B, ADR-014)',
  };
}

const sleepFor = (ms) => new Promise((done) => setTimeout(done, ms));
const signalFor = (ms) => AbortSignal.timeout(ms);

/**
 * The published posts, `body.data.posts` of the API's answer (undefined when it holds none, for the gate to refuse).
 * Throws the last error after three failed tries.
 * @param {string} url
 * @param {{ fetch?: Function, sleep?: (ms: number) => Promise<unknown>, timeout?: (ms: number) => unknown }} [io]
 * @returns {Promise<unknown>}
 */
export async function fetchPosts(url, io = {}) {
  const get = io.fetch ?? globalThis.fetch;
  const sleep = io.sleep ?? sleepFor;
  const timeout = io.timeout ?? signalFor;
  let lastError;
  for (let attempt = 1; attempt <= TRIES; attempt += 1) {
    try {
      const res = await get(url, { headers: { accept: "application/json" }, signal: timeout(TIMEOUT_MS) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const body = await res.json();
      return body?.data?.posts;
    } catch (err) {
      lastError = err;
      await sleep(BACKOFF_MS[attempt - 1]);
    }
  }
  throw lastError;
}

/** The API base, BLOG_API_URL first, with no trailing slash. */
function apiBase(env) {
  return (env.BLOG_API_URL || JOURNAL_API).replace(/\/+$/, "");
}

function parseArgs(argv) {
  const args = { mode: "sync", root: REPO, split: null };
  const modes = [];
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--check" || a === "--pages") modes.push(a.slice(2));
    else if (a === "--split" || a === "--root") {
      const value = argv[i + 1];
      if (!value || value.startsWith("--")) return null;
      if (a === "--split") {
        modes.push("split");
        args.split = value;
      } else args.root = value;
      i += 1;
    } else return null;
  }
  if (modes.length > 1) return null;
  if (modes.length) args.mode = modes[0];
  return args;
}

/** The committed snapshot: `{ missing: true }`, or its parsed value, or a throw naming the file. */
function readSnapshotFile(root) {
  const path = join(root, JOURNAL_SNAPSHOT);
  if (!existsSync(path)) return { missing: true, path };
  const text = readFileSync(path, "utf8");
  try {
    return { missing: false, path, text, value: JSON.parse(text) };
  } catch (e) {
    throw new Error(`${JOURNAL_SNAPSHOT} is not JSON (${e instanceof Error ? e.message : e})`);
  }
}

/** A missing snapshot is expected only before the switch (no registry yet); returns the reason it is fine, or throws. */
function missingSnapshot(root) {
  if (existsSync(join(root, REGISTRY))) throw new Error(`${REGISTRY} reads ${JOURNAL_SNAPSHOT}, which is missing`);
  return "no snapshot yet; the journal is still the article modules until task 8b.2e: nothing to check, no request";
}

/* ── the build's sync ─────────────────────────────────────────────────────────────────────────────── */

async function syncFromApi(root, env, out, io) {
  const url = `${apiBase(env)}${JOURNAL_POSTS_PATH}`;
  let posts;
  try {
    posts = await fetchPosts(url, io);
  } catch (e) {
    throw new Error(
      `could not reach ${url} (${e instanceof Error ? e.message : e}). Vercel keeps the last deploy; for an urgent ` +
        "code deploy set BLOG_SYNC=off for one deploy",
    );
  }
  const problems = validatePosts(posts, RULES);
  if (problems.length) throw new Error(problems.join("\n  "));
  const count = countProblem(posts.length);
  if (count) throw new Error(count);

  const file = readSnapshotFile(root);
  const previous = file.missing ? [] : Array.isArray(file.value?.posts) ? file.value.posts : [];
  const shrink = shrinkProblem(previous.length, posts.length);
  if (shrink && env.BLOG_ALLOW_SHRINK !== "1") throw new Error(shrink);

  for (const w of editorialWarnings(posts, RULES)) out.warn(w);
  const now = new Set(posts.map((p) => p.slug));
  for (const p of previous) {
    if (p && !now.has(p.slug)) out.warn(`post "${p.slug}" is no longer published; add a redirect if it was renamed (§10)`);
  }

  const changed = canonical(normalisePosts(posts)) !== canonical(normalisePosts(previous));
  if (changed) {
    mkdirSync(dirname(file.path), { recursive: true });
    writeFileSync(file.path, serialiseSnapshot(posts, syncNote(apiBase(env))));
  }
  out.log(`journal-sync: ${posts.length} posts${changed ? " (snapshot updated)" : " (unchanged)"}`);
}

function checkSnapshot(root, why, out) {
  const file = readSnapshotFile(root);
  if (file.missing) return out.log(`journal-sync: ${missingSnapshot(root)} (${why})`);
  const problems = snapshotProblems(file.value, RULES);
  if (problems.length) throw new Error(problems.join("\n  "));
  for (const w of editorialWarnings(file.value.posts, RULES)) out.warn(w);
  if (serialiseSnapshot(file.value.posts, file.value.generated) !== file.text) {
    out.warn(`${JOURNAL_SNAPSHOT} is not in the sync's order (edited by hand?); refresh it with the sync, never by hand`);
  }
  out.log(`journal-sync: ${file.value.posts.length} posts in ${JOURNAL_SNAPSHOT} pass; no request (${why})`);
}

/* ── by hand: --check and --split ─────────────────────────────────────────────────────────────────── */

async function check(root, env, out, io) {
  const file = readSnapshotFile(root);
  if (file.missing) throw new Error(`no snapshot at ${JOURNAL_SNAPSHOT} to compare`);
  const url = `${apiBase(env)}${JOURNAL_POSTS_PATH}`;
  let posts;
  try {
    posts = await fetchPosts(url, io);
  } catch (e) {
    throw new Error(`could not reach ${url} (${e instanceof Error ? e.message : e})`);
  }
  const problems = validatePosts(posts, RULES);
  if (problems.length) throw new Error(`the API's posts would not pass the gate:\n  ${problems.join("\n  ")}`);
  const filePosts = Array.isArray(file.value?.posts) ? file.value.posts : [];
  const diff = diffPosts(filePosts, posts);
  const lines = [
    ...diff.added.map((s) => `only in the API: "${s}" (published since the export? bring it to the contract before the flip)`),
    ...diff.removed.map((s) => `only in the file: "${s}"`),
    ...diff.changed.map((c) => `"${c.slug}": ${c.fields.join(", ")} differ`),
  ];
  if (lines.length) {
    for (const line of lines) out.log(`journal-sync --check: ${line}`);
    throw new Error(`journal-sync --check: ${lines.length} differences; the import is not proven`);
  }
  out.log(`journal-sync --check: identical (${posts.length} posts): the API returns ${JOURNAL_SNAPSHOT} unchanged`);
}

/** True when `dir` is `parent` or anywhere under it. */
function isInside(dir, parent) {
  const rel = relative(resolve(parent), resolve(dir));
  return rel === "" || (rel !== ".." && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
}

function split(root, dir, out) {
  if (isInside(dir, REPO) || isInside(dir, root)) {
    throw new Error(`--split ${dir}: write the files outside the repository (it is public; they are never committed)`);
  }
  const file = readSnapshotFile(root);
  if (file.missing) throw new Error(`no snapshot at ${JOURNAL_SNAPSHOT} to split`);
  const problems = snapshotProblems(file.value, RULES);
  if (problems.length) throw new Error(problems.join("\n  "));
  mkdirSync(dir, { recursive: true });
  const posts = normalisePosts(file.value.posts);
  for (const post of posts) writeFileSync(join(dir, `${post.slug}.json`), `${JSON.stringify(post, null, 2)}\n`);
  out.log(`journal-sync --split: ${posts.length} posts written to ${dir}; never commit them`);
}

/* ── postbuild: every post became a prerendered page (§8.2 row 26) ────────────────────────────────── */

function checkPages(root, out) {
  const file = readSnapshotFile(root);
  if (file.missing) return out.log(`journal-pages: ${missingSnapshot(root)}`);
  const problems = snapshotProblems(file.value, RULES);
  if (problems.length) throw new Error(problems.join("\n  "));
  const manifestPath = join(root, ROUTES_MANIFEST);
  if (!existsSync(manifestPath)) throw new Error(`${ROUTES_MANIFEST.split(sep).join("/")} is missing: run after next build`);
  /* The redirect wins (§10): Next answers a redirect before any page, and the adapter drops the post. Only an apex
     rule counts, as the built manifest holds it; a host-conditioned (www) twin leaves the page expected. */
  const redirects = new Set(
    (JSON.parse(readFileSync(manifestPath, "utf8")).redirects ?? []).filter((r) => !r.has).map((r) => r.source),
  );
  const expected = [];
  for (const post of file.value.posts) {
    if (redirects.has(`/stories/${post.slug}`)) {
      out.log(`journal-pages: note: "${post.slug}" is a redirect source; the redirect wins, no page expected`);
    } else expected.push(post.slug);
  }
  const missing = expected.filter((slug) => {
    const page = join(root, PAGES_DIR, `${slug}.html`);
    return !existsSync(page) || statSync(page).size === 0;
  });
  if (missing.length) {
    throw new Error(
      missing.map((s) => `no prerendered page for "${s}" (${join(PAGES_DIR, `${s}.html`).split(sep).join("/")})`).join("\n  "),
    );
  }
  if (expected.length < 4) throw new Error(`${expected.length} journal pages; at least 4 (every guide offers three others)`);
  out.log(`journal-pages: ${file.value.posts.length} posts, ${expected.length} prerendered pages`);
}

/* ── the entry ────────────────────────────────────────────────────────────────────────────────────── */

/**
 * Runs the sync (or --check, --split, --pages) and returns the exit code: 0, 1 on any failure, 2 on bad arguments.
 * @param {string[]} argv
 * @param {{ env?: Record<string, string | undefined>, fetch?: Function, sleep?: (ms: number) => Promise<unknown>,
 *   timeout?: (ms: number) => unknown, log?: (line: string) => void, error?: (line: string) => void,
 *   source?: "snapshot" | "api" }} [io]
 * @returns {Promise<number>}
 */
export async function run(argv, io = {}) {
  const env = io.env ?? process.env;
  const log = io.log ?? console.log;
  const error = io.error ?? console.error;
  const args = parseArgs(argv);
  if (!args) {
    error(USAGE);
    return 2;
  }
  const tag = args.mode === "pages" ? "journal-pages" : args.mode === "sync" ? "journal-sync" : `journal-sync --${args.mode}`;
  const out = { log, warn: (line) => log(`${tag}: warning: ${line}`) };
  try {
    if (args.mode === "pages") checkPages(args.root, out);
    else if (args.mode === "split") split(args.root, args.split, out);
    else if (args.mode === "check") await check(args.root, env, out, io);
    else {
      const { mode, why } = resolveMode(env, io.source ?? JOURNAL_SOURCE);
      if (mode === "api") await syncFromApi(args.root, env, out, io);
      else checkSnapshot(args.root, why, out);
    }
    return 0;
  } catch (e) {
    const message = e instanceof Error ? e.message : String(e);
    error(message.startsWith(tag) ? message : `${tag}: FAILED: ${message}`);
    return 1;
  }
}

/* Run as a script (the build steps spawn it), not when a test imports it. realpath, because the loader resolves
   symlinks in import.meta.url and argv[1] keeps them: a mismatch would skip run() and pass silently. */
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await run(process.argv.slice(2));
}
