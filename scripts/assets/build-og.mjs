#!/usr/bin/env node
// Writes the stable-URL images machines fetch, from DS files only (task 1.5, ADR-010, assets.md §3):
//
//   public/og.png                  default Open Graph card (URL kept from the old site)
//   public/og/kheelu.jpg           Open Graph card for Home and the product page (copy: kheelu-on-fur.jpg)
//   public/media/kheelu-front.jpg  Product JSON-LD image (stable URL)
//   public/brand/logo-mark.png     Organization logo, the K mark (URL kept from the old site)
//   src/app/icon.png               browser icon (Next file convention)
//   src/app/apple-icon.png         Apple touch icon (Next file convention)
//   src/app/favicon.ico            /favicon.ico keeps answering (url-map §3), now the DS favicons
//
//   node scripts/assets/build-og.mjs
//
// Rules: cards are 1200 x 630 (DS 06-surfaces.md:15) and at most 200 KB; they carry no text
// (pixels carry claims, lessons §6), only the DS photo on its own ground. App icons are opaque
// (lessons §2: the iOS icon must be opaque), flattened onto the ground of the DS app icon. Every
// file carries an EXIF ImageDescription naming this script and its DS source. Nothing is written
// into design-system/. test/guards/generated-icons.test.ts checks the outputs and their drift.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DS_ASSETS = "design-system/project/assets";

const OG = { width: 1200, height: 630 }; // DS 06-surfaces.md:15, "WhatsApp share / OG image"
const MAX_CARD_BYTES = 200 * 1024; // task 1.5 acceptance 3
const MEDIA_SIZE = 1200; // square product image; Google asks for at least 50,000 pixels
const LOGO_SIZE = 512; // the size of the /brand/logo-mark.png it replaces
const FLAT_TOLERANCE = 3; // per channel, for "one flat ground" (JPEG noise)

const PHOTO = "Kheelu/kheelu-on-fur.jpg";
const MARK = "Logo/kheelona-mark.svg";
const APP_ICON = "Logo/kheelona-app-icon.svg";

const header = (source) => `GENERATED by scripts/assets/build-og.mjs, do not edit; source ${DS_ASSETS}/${source}`;
const tagged = (img, description) => img.withExif({ IFD0: { ImageDescription: description } });

/** The colour of a photo's border, which must be one flat ground so a card can extend it. */
async function flatGround(asset, source) {
  const { data, info } = await sharp(asset(source)).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height } = info;
  const at = (x, y) => (y * width + x) * 3;
  const ring = [];
  for (let x = 0; x < width; x++) ring.push(at(x, 0), at(x, 1), at(x, height - 1), at(x, height - 2));
  for (let y = 0; y < height; y++) ring.push(at(0, y), at(1, y), at(width - 1, y), at(width - 2, y));
  const ground = [0, 1, 2].map((c) => Math.round(ring.reduce((s, i) => s + data[i + c], 0) / ring.length));
  for (const i of ring) {
    for (let c = 0; c < 3; c++) {
      if (Math.abs(data[i + c] - ground[c]) > FLAT_TOLERANCE) {
        throw new Error(`build-og: ${source}: border is not one flat ground (pixel ${i / 3} is ${[...data.subarray(i, i + 3)]}, ground ${ground})`);
      }
    }
  }
  return { r: ground[0], g: ground[1], b: ground[2] };
}

/** The DS app icon's ground colour and the share of its height the K takes. */
function appIconGeometry(asset) {
  const svg = readFileSync(asset(APP_ICON), "utf8");
  const box = Number(svg.match(/<svg\b[^>]*\bviewBox="0 0 ([\d.]+) [\d.]+"/)?.[1]);
  const fill = svg.match(/<rect\b[^>]*\bfill="(#[0-9a-fA-F]{6})"/)?.[1];
  const scale = Number(svg.match(/<g\b[^>]*\btransform="[^"]*\bscale\(([\d.]+)\)"/)?.[1]);
  const markHeight = Number(readFileSync(asset(MARK), "utf8").match(/<svg\b[^>]*\bviewBox="[\d.]+ [\d.]+ [\d.]+ ([\d.]+)"/)?.[1]);
  if (!box || !fill || !scale || !markHeight) throw new Error(`build-og: ${APP_ICON}: cannot read the ground, the K's scale or the mark's height`);
  const n = parseInt(fill.slice(1), 16);
  return { ground: { r: n >> 16, g: (n >> 8) & 255, b: n & 255 }, markShare: (markHeight * scale) / box };
}

async function card(asset, ground, format) {
  const img = sharp(asset(PHOTO)).resize(OG.width, OG.height, { fit: "contain", background: ground });
  const encoded = format === "png" ? img.png({ palette: true, effort: 10, compressionLevel: 9 }) : img.jpeg({ quality: 85, mozjpeg: true });
  return tagged(encoded, header(PHOTO)).toBuffer();
}

async function logoMark(asset, markShare) {
  const svg = readFileSync(asset(MARK));
  const height = Math.round(LOGO_SIZE * markShare);
  const intrinsic = Number(svg.toString("utf8").match(/<svg\b[^>]*\bheight="([\d.]+)"/)?.[1]);
  const k = await sharp(svg, { density: Math.ceil((72 * 2 * height) / intrinsic) }).resize({ height }).png().toBuffer();
  const { width } = await sharp(k).metadata();
  const top = Math.floor((LOGO_SIZE - height) / 2);
  const left = Math.floor((LOGO_SIZE - width) / 2);
  const clear = { r: 0, g: 0, b: 0, alpha: 0 };
  const img = sharp(k).extend({ top, bottom: LOGO_SIZE - height - top, left, right: LOGO_SIZE - width - left, background: clear });
  return tagged(img.png({ compressionLevel: 9 }), `${header(MARK)} (sized in the square as ${APP_ICON})`).toBuffer();
}

/** An opaque PNG of a DS icon, flattened onto the DS app icon's ground. Saved as RGBA with every
 *  alpha at 255: Turbopack's icon pipeline refuses RGB PNGs ("The PNG is not in RGBA format"), and an
 *  all-255 alpha channel is still opaque for iOS (lessons §2). */
function opaqueIcon(asset, source, ground) {
  const img = sharp(asset(source)).flatten({ background: ground }).ensureAlpha(1).png({ compressionLevel: 9 });
  return tagged(img, `${header(source)} (flattened onto the ground of ${APP_ICON})`).toBuffer();
}

/** An ICO container holding PNG images (6-byte header, 16-byte entries, then the data). */
async function ico(pngs) {
  const head = Buffer.alloc(6);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(pngs.length, 4);
  let offset = 6 + 16 * pngs.length;
  const entries = [];
  for (const png of pngs) {
    const { width, height, channels } = await sharp(png).metadata();
    const e = Buffer.alloc(16);
    e[0] = width >= 256 ? 0 : width;
    e[1] = height >= 256 ? 0 : height;
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(channels * 8, 6);
    e.writeUInt32LE(png.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += png.length;
    entries.push(e);
  }
  return Buffer.concat([head, ...entries, ...pngs]);
}

/** Every output: its repo path and how it is made from the DS files. */
export const IMAGE_OUTPUTS = [
  { path: "public/og.png", make: (ctx) => card(ctx.asset, ctx.photoGround, "png"), card: true },
  { path: "public/og/kheelu.jpg", make: (ctx) => card(ctx.asset, ctx.photoGround, "jpeg"), card: true },
  {
    path: "public/media/kheelu-front.jpg",
    make: (ctx) =>
      tagged(
        sharp(ctx.asset(PHOTO)).resize(MEDIA_SIZE, MEDIA_SIZE, { fit: "contain", background: ctx.photoGround }).jpeg({ quality: 85, mozjpeg: true }),
        header(PHOTO),
      ).toBuffer(),
  },
  { path: "public/brand/logo-mark.png", make: (ctx) => logoMark(ctx.asset, ctx.app.markShare) },
  { path: "src/app/icon.png", make: (ctx) => opaqueIcon(ctx.asset, "Logo/favicon-48.png", ctx.app.ground) },
  { path: "src/app/apple-icon.png", make: (ctx) => opaqueIcon(ctx.asset, "Logo/apple-touch-icon-180.png", ctx.app.ground) },
  {
    path: "src/app/favicon.ico",
    make: async (ctx) =>
      ico([await opaqueIcon(ctx.asset, "Logo/favicon-32.png", ctx.app.ground), await opaqueIcon(ctx.asset, "Logo/favicon-48.png", ctx.app.ground)]),
  },
];

/**
 * Renders every output in memory. `asset` maps a path under design-system/project/assets to a file
 * (tests point it at fixtures). Resolves to [{ path, buffer }].
 */
export async function buildImages({ asset = (rel) => join(ROOT, DS_ASSETS, rel) } = {}) {
  const ctx = { asset, photoGround: await flatGround(asset, PHOTO), app: appIconGeometry(asset) };
  const out = [];
  for (const o of IMAGE_OUTPUTS) {
    const buffer = await o.make(ctx);
    if (o.card && buffer.length > MAX_CARD_BYTES) throw new Error(`build-og: ${o.path} is ${buffer.length} bytes, over ${MAX_CARD_BYTES}`);
    out.push({ path: o.path, buffer });
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, buffer } of await buildImages()) {
    if (path.startsWith("design-system/")) throw new Error(`build-og: refusing to write into design-system/ (${path})`);
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), buffer);
    console.log(`build-og: wrote ${path} (${buffer.length} bytes)`);
  }
}
