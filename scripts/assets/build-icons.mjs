#!/usr/bin/env node
// Writes src/assets/icons.generated.ts: the path data of every DS icon, keyed by name, for the
// Icon primitive (task 1.5, ADR-010, brief §9.12 "one icon set").
//
//   node scripts/assets/build-icons.mjs
//
// Source: design-system/project/assets/Icons/*.svg (76 Phosphor Bold icons, MIT licence), read-only.
// The extraction is the one mockup/build.mjs uses for the approved pages: every <path> with its
// d attribute, the file's fill dropped (the Icon fills with currentColor). Anything that extraction
// could not carry faithfully (no path, several paths, another attribute, another viewBox) stops
// the script instead of being dropped silently. test/guards/generated-icons.test.ts regenerates
// in memory and fails on drift.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ICONS_DIR = join(ROOT, "design-system", "project", "assets", "Icons");
const OUT = join(ROOT, "src", "assets", "icons.generated.ts");

// mockup/build.mjs, `icon()`: the path elements it inlines.
const PATH_ELEMENT = /<path [^>]*?d="[^"]+"[^>]*?(?:\/>|><\/path>)/g;

/** The single path's d of one DS icon; throws on anything it cannot carry. */
function iconPath(name, svg) {
  const paths = svg.match(PATH_ELEMENT) ?? [];
  if (paths.length === 0) throw new Error(`build-icons: ${name}: no paths`);
  if (paths.length > 1) throw new Error(`build-icons: ${name}: ${paths.length} paths; the icon set carries one d per icon`);
  const attrs = [...paths[0].matchAll(/\s([a-zA-Z:-]+)="([^"]*)"/g)];
  const extra = attrs.map(([, attr]) => attr).filter((attr) => attr !== "d" && attr !== "fill");
  if (extra.length) throw new Error(`build-icons: ${name}: path attribute ${extra.join(", ")} would be dropped`);
  return attrs.find(([, attr]) => attr === "d")[2];
}

/** The content of icons.generated.ts for the icons in `iconsDir`. */
export function generateIcons({ iconsDir = ICONS_DIR } = {}) {
  const names = readdirSync(iconsDir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.slice(0, -4))
    .sort();
  let viewBox;
  const entries = names.map((name) => {
    const svg = readFileSync(join(iconsDir, `${name}.svg`), "utf8");
    const vb = svg.match(/<svg\b[^>]*\bviewBox="([^"]+)"/)?.[1];
    viewBox ??= vb;
    if (vb !== viewBox) throw new Error(`build-icons: ${name}: viewBox "${vb}" differs from the set's "${viewBox}"`);
    return [name, iconPath(name, svg)];
  });
  const source = relative(ROOT, iconsDir).split("\\").join("/");
  return [
    `// GENERATED by scripts/assets/build-icons.mjs, do not edit; source ${source}/*.svg`,
    `// (${names.length} Phosphor Bold icons, MIT licence; path extraction as mockup/build.mjs). Regenerate: node scripts/assets/build-icons.mjs`,
    "",
    "/** The viewBox every DS icon shares. */",
    `export const ICON_VIEWBOX = ${JSON.stringify(viewBox)};`,
    "",
    "/** The name of a DS icon; anything else is a DS gap (G-12). */",
    "export type IconName =",
    ...names.map((name, i) => `  | ${JSON.stringify(name)}${i === names.length - 1 ? ";" : ""}`),
    "",
    "/** The path data of each DS icon, drawn on ICON_VIEWBOX and filled with currentColor. */",
    "export const ICON_PATHS: Readonly<Record<IconName, string>> = {",
    ...entries.map(([name, d]) => `  ${JSON.stringify(name)}: ${JSON.stringify(d)},`),
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUT, generateIcons());
  console.log(`build-icons: wrote ${relative(ROOT, OUT)}`);
}
