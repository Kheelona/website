#!/usr/bin/env node
// Writes src/styles/generated/compose.css, the manifest of colocated component CSS (task 1.2, architecture §4.3).
//
//   node scripts/assets/build-compose-css.mjs     (also run by the predev and prebuild steps, 20-compose-css.mjs)
//
// Composition classes (ks-) live in one CSS file beside the component that renders them. This script imports
// every such file into one manifest, in a fixed order: ui, then sections, then chrome, then layouts, alphabetical
// by path within each, so later layers can refine earlier ones and the cascade never depends on the file system.
// site.css imports the manifest after motion.css and before Tailwind. An empty manifest is valid (wave 1, before
// any component exists). The output is git-ignored: it changes whenever a component adds CSS.

import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const COMPOSE_OUT = "src/styles/generated/compose.css";
/** The layers, relative to src/, in cascade order. */
export const LAYERS = ["components/ui", "components/sections", "components/chrome", "layouts"];

function walk(dir) {
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return [];
  }
  return names.flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** Component CSS files under `srcDir`, as paths relative to it ("components/ui/Photo/photo.css"), in cascade order. */
export function collectComposeFiles(srcDir) {
  return LAYERS.flatMap((layer) =>
    walk(join(srcDir, layer))
      .filter((p) => p.endsWith(".css"))
      .map((p) => relative(srcDir, p).split(sep).join("/"))
      .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)),
  );
}

export function renderComposeCss(files) {
  return [
    "/* GENERATED by scripts/assets/build-compose-css.mjs, do not edit; source the colocated component CSS under\n",
    `   src/${LAYERS.join(", src/")} (in that order). Git-ignored; rewritten by the predev and prebuild steps. */\n`,
    ...files.map((f) => `@import "../../${f}";\n`),
  ].join("");
}

/** `path`'s text, or undefined when there is none. */
function readIfAny(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return undefined;
  }
}

/**
 * Writes the manifest so that a reader only ever sees the old one or the new one, never an emptied file: the guards
 * rebuild it while other Vitest workers compile site.css, and a dev server may read it at any time. A current
 * manifest is left untouched (no rewrite, no new mtime); a stale one is written beside it under a name no CSS glob
 * matches, then renamed over it (atomic within one folder).
 */
export function buildComposeCss({ root = ROOT, write = true } = {}) {
  const files = collectComposeFiles(join(root, "src"));
  const path = join(root, COMPOSE_OUT);
  const css = renderComposeCss(files);
  if (write && readIfAny(path) !== css) {
    mkdirSync(dirname(path), { recursive: true });
    const temp = join(dirname(path), `.${basename(path)}.${process.pid}-${randomBytes(6).toString("hex")}.tmp`);
    try {
      writeFileSync(temp, css);
      renameSync(temp, path);
    } finally {
      rmSync(temp, { force: true });
    }
  }
  return { path, files };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { path, files } = buildComposeCss();
  console.log(`${relative(ROOT, path)}: ${files.length} component CSS file(s)`);
}
