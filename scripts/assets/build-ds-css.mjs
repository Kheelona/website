#!/usr/bin/env node
// Writes the CSS derivatives of the design system's tokens (task 1.2, ADR-002, architecture §4.3).
//
//   node scripts/assets/build-ds-css.mjs
//
// design-system/ is read-only, so nothing is written there. Two files come out, both committed and both
// re-derived by test/guards/generated-css.test.ts:
//   src/styles/generated/ds-tokens.css   tokens.css without its four @font-face rules (fonts.css serves the faces
//                                         from public/fonts instead of design-system/project/fonts)
//   src/styles/generated/type-steps.css  ks-type-<style> for each of the 19 kh- type classes of tokens.css, plus
//                                         ks-type-<style>@sm|lg|xl inside the DS breakpoint queries, so a page can
//                                         step a DS type style up on wider screens without restating a pixel size

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const TOKENS_CSS = "design-system/project/tokens.css";
export const BUNDLE_CSS = "design-system/project/components/bundle.css";
export const DS_TOKENS_OUT = "src/styles/generated/ds-tokens.css";
export const TYPE_STEPS_OUT = "src/styles/generated/type-steps.css";

/** The breakpoint names of the Tailwind theme (architecture §4.2), smallest first. */
const BREAKPOINT_NAMES = ["sm", "md", "lg", "xl"];
/** The steps the mockup restates type at (720, 900 and 1024 px); 768 is SectionHeading's own step in bundle.css. */
export const TYPE_STEP_BREAKPOINTS = ["sm", "lg", "xl"];

const header = (what) =>
  `/* GENERATED by scripts/assets/build-ds-css.mjs, do not edit; source ${TOKENS_CSS}.\n   ${what} */\n`;

/** The four min-width breakpoints bundle.css hard-codes (DS gap G-03), named sm, md, lg, xl. */
export function dsBreakpoints(bundleCss) {
  const widths = [...new Set([...bundleCss.matchAll(/@media \(min-width: (\d+)px\)/g)].map((m) => Number(m[1])))].sort((a, b) => a - b);
  if (widths.length !== BREAKPOINT_NAMES.length) {
    throw new Error(`bundle.css: expected ${BREAKPOINT_NAMES.length} min-width breakpoints, found ${widths.join(", ") || "none"}`);
  }
  return widths.map((minWidth, i) => ({ name: BREAKPOINT_NAMES[i], minWidth }));
}

/** tokens.css minus its @font-face rules (one per line in the delivered file). */
export function renderDsTokens(tokensCss) {
  const lines = tokensCss.split("\n");
  const kept = lines.filter((l) => !l.startsWith("@font-face"));
  if (lines.length - kept.length !== 4) throw new Error(`tokens.css: expected 4 @font-face rules, found ${lines.length - kept.length}`);
  if (/@font-face/.test(kept.join("\n"))) throw new Error("tokens.css: an @font-face rule spans several lines; update build-ds-css.mjs");
  return header("tokens.css without its four @font-face rules; the faces are in fonts.css (scripts/assets/build-fonts.mjs).") + kept.join("\n");
}

/** The kh- type classes of tokens.css: one-line rules `.kh-<style> { <declarations> }`. */
export function typeStyles(tokensCss) {
  const styles = [...tokensCss.matchAll(/^\.kh-([a-z0-9-]+) \{ ([^}]*) \}$/gm)].map((m) => ({ name: m[1], decls: m[2].trim() }));
  if (styles.length !== 19) throw new Error(`tokens.css: expected the 19 kh- type classes, found ${styles.length}`);
  return styles;
}

export function renderTypeSteps(tokensCss, bundleCss) {
  const styles = typeStyles(tokensCss);
  const steps = dsBreakpoints(bundleCss).filter((b) => TYPE_STEP_BREAKPOINTS.includes(b.name));
  const out = [
    header(
      `Responsive type steps: ks-type-<style> is kh-<style>; ks-type-<style>@<bp> applies it from ${steps.map((s) => `${s.name} (${s.minWidth}px)`).join(", ")}.`,
    ),
  ];
  for (const s of styles) out.push(`.ks-type-${s.name} { ${s.decls} }\n`);
  for (const step of steps) {
    out.push(`@media (min-width: ${step.minWidth}px) {\n`);
    for (const s of styles) out.push(`  .ks-type-${s.name}\\@${step.name} { ${s.decls} }\n`);
    out.push("}\n");
  }
  return out.join("");
}

export function buildDsCss({ root = ROOT, write = true } = {}) {
  const tokensCss = readFileSync(join(root, TOKENS_CSS), "utf8");
  const bundleCss = readFileSync(join(root, BUNDLE_CSS), "utf8");
  const files = { [DS_TOKENS_OUT]: renderDsTokens(tokensCss), [TYPE_STEPS_OUT]: renderTypeSteps(tokensCss, bundleCss) };
  if (write) {
    for (const [path, text] of Object.entries(files)) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), text);
    }
  }
  return { files };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { files } = buildDsCss();
  for (const [path, text] of Object.entries(files)) console.log(`${path}  ${Buffer.byteLength(text)} bytes`);
}
