#!/usr/bin/env node
// Writes the hero photo's crops (task Q2.1, D064 item 4; assets.md §3). Home's hero picture is the DS photo library's
// "Kabir · block rocket" (design-system 10-pages.md lists kabir-02 among the web-hero photos), cut from its 2K master
// (DS Photo library README: the masters are "for decks, print and crops"; the web file is 1500 x 837, too few pixels
// for a tight crop on a retina laptop):
//
//   src/assets/hero/kabir-02-block-rocket-4x5.jpg     the hero's picture from 720 px: the DS photo frame's 4:5, 1200 x 1500
//   src/assets/hero/kabir-02-block-rocket-16x10.jpg   under 720 px, right under the trust line (D061 item 1's place): 16:10,
//                                                     1600 x 1000
//
//   node scripts/assets/build-hero-crops.mjs
//
// Rules: a crop keeps faces and Kheelu whole and off the edge (design-system 03-cast.md, "Using the library"), never
// mirrored, retouched or recoloured; only cut and scaled. The script refuses a crop window that cuts the boy, his head
// or Kheelu, or runs off the master. Every file carries an EXIF ImageDescription naming this script and its DS source.
// Nothing is written into design-system/. test/guards/generated-hero-crops.test.ts checks the outputs and their drift.
// next/image serves the AVIF and WebP renditions at layout widths from these files (assets.md §3). The photo, the
// subjects and the crop windows are hero-crops.mjs's, shared with the guard and the first-screen spec.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";
import { cropWindow, HERO_CROPS, HERO_SOURCE, MASTER_SIZE, OFF_THE_EDGE, subjectsIn } from "./hero-crops.mjs";

/** @typedef {import("./hero-crops.mjs").HeroCrop} HeroCrop */
/** @typedef {import("./hero-crops.mjs").Size} Size */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DS_ASSETS = "design-system/project/assets";

const header = `GENERATED by scripts/assets/build-hero-crops.mjs, do not edit; source ${DS_ASSETS}/${HERO_SOURCE}`;

/**
 * Throws unless the window lies inside the master and keeps every subject whole and off the edge.
 * @param {HeroCrop} crop
 * @param {Size} master
 */
function checkCrop(crop, master) {
  const w = cropWindow(crop, master);
  if (w.left < 0 || w.top < 0 || w.left + w.width > master.width || w.top + w.height > master.height) {
    throw new Error(`build-hero-crops: ${crop.path}: the window ${JSON.stringify(w)} runs off the ${master.width} x ${master.height} master`);
  }
  for (const [name, box] of Object.entries(subjectsIn(crop, master))) {
    const [l, t, r, b] = box;
    if (l < OFF_THE_EDGE || t < OFF_THE_EDGE || r > 1 - OFF_THE_EDGE || b > 1 - OFF_THE_EDGE) {
      throw new Error(`build-hero-crops: ${crop.path}: ${name} is not whole and off the edge (${box.map((v) => v.toFixed(3)).join(", ")})`);
    }
  }
  return w;
}

/**
 * Renders every crop in memory. `asset` maps a path under design-system/project/assets to a file; `crops` defaults to
 * HERO_CROPS (tests pass a broken one). Resolves to [{ path, buffer }].
 * @param {{ asset?: (rel: string) => string, crops?: readonly HeroCrop[] }} [options]
 * @returns {Promise<{ path: string, buffer: Buffer }[]>}
 */
export async function buildHeroCrops({ asset = (rel) => join(ROOT, DS_ASSETS, rel), crops = HERO_CROPS } = {}) {
  const source = asset(HERO_SOURCE);
  const { width, height } = await sharp(source).metadata();
  if (width !== MASTER_SIZE.width || height !== MASTER_SIZE.height) {
    throw new Error(`build-hero-crops: ${HERO_SOURCE} is ${width} x ${height}, not the ${MASTER_SIZE.width} x ${MASTER_SIZE.height} master the subjects were read on`);
  }
  const windows = crops.map((crop) => checkCrop(crop, MASTER_SIZE));
  return Promise.all(
    crops.map(async (crop, i) => ({
      path: crop.path,
      buffer: await sharp(source)
        .extract(windows[i])
        .resize(crop.width, crop.height)
        .jpeg({ quality: 90, mozjpeg: true })
        .withExif({ IFD0: { ImageDescription: header } })
        .toBuffer(),
    })),
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, buffer } of await buildHeroCrops()) {
    if (path.startsWith("design-system/")) throw new Error(`build-hero-crops: refusing to write into design-system/ (${path})`);
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), buffer);
    console.log(`build-hero-crops: wrote ${path} (${buffer.length} bytes)`);
  }
}
