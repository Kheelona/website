/** The width a card and a photo are both shrunk to before they are compared (the card is then 63 rows). */
const MATCH_WIDTH = 120;
/** The largest mean grey difference (0-255) at which a card still counts as a cut of a photo. Measured 2026-10-13: each
 *  card 1.6 to 4.4 against its own photo (the band's top falls between two shrunk rows), at least 45 against every other
 *  head photo, and each photo contained in a card on a flat ground at least 15 (the 16:9 photos, whose side bars are
 *  narrow). */
const CUT_TOLERANCE = 10;

/** A picture shrunk to MATCH_WIDTH, grey, as raw rows. */
async function shrunk(input: Buffer | string) {
  const { data, info } = await sharp(input).resize({ width: MATCH_WIDTH }).greyscale().raw().toBuffer({ resolveWithObject: true });
  return { data, rows: info.height };
}

/**
 * Where a card sits in a photo, as the photo's own pixels: the card's rows slid down the photo's rows, both at one
 * width, and the closest window's mean grey difference. Small only when the card is that photo cut across its full
 * width: a different photo, a photo set on a ground or bordered, or text drawn over it all land far off.
 */
async function cutDifference(card: Buffer, photo: { data: Buffer; rows: number }) {
  const c = await shrunk(card);
  let best = Infinity;
  for (let top = 0; top + c.rows <= photo.rows; top++) {
    let sum = 0;
    for (let i = 0; i < c.data.length; i++) sum += Math.abs(c.data[i] - photo.data[top * MATCH_WIDTH + i]);
    best = Math.min(best, sum / c.data.length);
  }
  return best;
}

