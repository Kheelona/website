// Guard for the generated icon set and the generated stable-URL images (task 1.5, ADR-010).
//
//   1. src/assets/icons.generated.ts (scripts/assets/build-icons.mjs): one entry per DS icon,
//      the same path data the approved mockup inlines, never stale.
//   2. The images scripts/assets/build-og.mjs writes: the Open Graph cards, the JSON-LD product
//      image, the Organization logo and the app icons. Sizes, byte budgets, opacity, the header
//      naming source and script, and drift against a fresh in-memory render.
//
// Expectations are derived from the DS files and the built mockup pages, never from the scripts.
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import sharp from "sharp";
import { ICON_PATHS, ICON_VIEWBOX } from "@/assets/icons.generated";
import { generateIcons } from "../../scripts/assets/build-icons.mjs";
import { buildImages, IMAGE_OUTPUTS } from "../../scripts/assets/build-og.mjs";

const REPO = join(__dirname, "..", "..");
const DS = join(REPO, "design-system", "project");
const ICONS_DIR = join(DS, "assets", "Icons");
const read = (p: string) => readFileSync(join(REPO, p));

const dsIconNames = readdirSync(ICONS_DIR)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort();

describe("icons.generated.ts: the one icon set (brief §9.12)", () => {
  it("has exactly one entry per DS icon file, 76 in all", () => {
    expect(dsIconNames).toHaveLength(76);
    expect(Object.keys(ICON_PATHS).sort()).toEqual(dsIconNames);
  });

  it("keeps each DS icon's path data verbatim, on the DS viewBox", () => {
    for (const name of dsIconNames) {
      const svg = readFileSync(join(ICONS_DIR, `${name}.svg`), "utf8");
      const d = svg.match(/<path\b[^>]*\bd="([^"]+)"/)?.[1];
      expect(ICON_PATHS[name as keyof typeof ICON_PATHS], name).toBe(d);
      expect(svg).toContain(`viewBox="${ICON_VIEWBOX}"`);
    }
  });

  it("renders every icon the approved mockup inlines byte for byte (mockup/build.mjs extraction)", () => {
    const pages = readdirSync(join(REPO, "mockup")).filter((f) => f.endsWith(".html"));
    const generated = new Set(Object.values(ICON_PATHS).map((d) => `<path d="${d}"></path>`));
    let seen = 0;
    for (const page of pages) {
      const html = readFileSync(join(REPO, "mockup", page), "utf8");
      for (const m of html.matchAll(/<svg class="kh-icon[^"]*" viewBox="([^"]+)" aria-hidden="true" focusable="false">(.*?)<\/svg>/g)) {
        seen++;
        expect(m[1]).toBe(ICON_VIEWBOX);
        expect(generated.has(m[2]), `${page}: ${m[2].slice(0, 60)}`).toBe(true);
      }
    }
    expect(seen).toBeGreaterThan(100);
  });

  it("names every {{icon:…}} token the approved mockup pages use", () => {
    const dir = join(REPO, "mockup");
    const sources = [
      ...readdirSync(join(dir, "pages")).map((f) => join(dir, "pages", f)),
      ...readdirSync(join(dir, "partials")).map((f) => join(dir, "partials", f)),
    ];
    const used = new Set<string>();
    for (const f of sources) {
      for (const m of readFileSync(f, "utf8").matchAll(/\{\{icon(?:-chev)?:([a-z0-9-]+)\}\}/g)) used.add(m[1]);
    }
    expect(used.size).toBeGreaterThan(40);
    for (const name of used) expect(Object.keys(ICON_PATHS), name).toContain(name);
  });

  it("is up to date: regenerating in memory gives the committed file", () => {
    expect(generateIcons()).toBe(read("src/assets/icons.generated.ts").toString("utf8"));
  });

  it("carries the generated-file header naming its script and source", () => {
    const first = read("src/assets/icons.generated.ts").toString("utf8").split("\n")[0];
    expect(first).toMatch(/^\/\/ GENERATED by scripts\/assets\/build-icons\.mjs, do not edit; source design-system\/project\/assets\/Icons\//);
  });
});

describe("build-icons.mjs refuses what it cannot carry faithfully", () => {
  let dir: string;
  const ok = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="#2a2118"><path d="M1,1H2Z"></path></svg>';
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "ks-icons-"));
    writeFileSync(join(dir, "fine.svg"), ok);
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it("accepts a well-formed DS icon", () => {
    expect(generateIcons({ iconsDir: dir })).toContain('"fine": "M1,1H2Z"');
  });

  it("fails on an icon with no path", () => {
    writeFileSync(join(dir, "empty.svg"), '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"></svg>');
    expect(() => generateIcons({ iconsDir: dir })).toThrow(/empty: no paths/);
  });

  it("fails on a path attribute other than d and fill (it would be dropped)", () => {
    writeFileSync(join(dir, "rule.svg"), ok.replace("<path ", '<path fill-rule="evenodd" '));
    expect(() => generateIcons({ iconsDir: dir })).toThrow(/rule: .*fill-rule/);
  });

  it("fails on an icon with several paths (one d per icon)", () => {
    writeFileSync(join(dir, "two.svg"), ok.replace("</svg>", '<path d="M3,3Z"></path></svg>'));
    expect(() => generateIcons({ iconsDir: dir })).toThrow(/two: 2 paths/);
  });

  it("fails on a viewBox other than the set's", () => {
    writeFileSync(join(dir, "wide.svg"), ok.replace("0 0 256 256", "0 0 24 24"));
    expect(() => generateIcons({ iconsDir: dir })).toThrow(/wide: viewBox/);
  });
});

