const KB = 1024;
const HEADER = "GENERATED by scripts/assets/build-og.mjs, do not edit; source design-system/project/assets/";

async function exifText(buf: Buffer): Promise<string> {
  const { exif } = await sharp(buf).metadata();
  return exif ? exif.toString("latin1") : "";
}

/** Decoded RGBA pixels, so two encodes of the same picture can be compared across platforms. */
async function rgba(buf: Buffer) {
  const { data, info } = await sharp(buf).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
}

async function meanAbsDiff(a: Buffer, b: Buffer): Promise<number> {
  const [x, y] = await Promise.all([rgba(a), rgba(b)]);
  expect([x.width, x.height]).toEqual([y.width, y.height]);
  let sum = 0;
  for (let i = 0; i < x.data.length; i++) sum += Math.abs(x.data[i] - y.data[i]);
  return sum / x.data.length;
}

/** The ICO container: a 6-byte header, a 16-byte entry per image, then PNG data. */
function icoEntries(buf: Buffer) {
  expect(buf.readUInt16LE(0)).toBe(0);
  expect(buf.readUInt16LE(2)).toBe(1);
  const count = buf.readUInt16LE(4);
  return Array.from({ length: count }, (_, i) => {
    const at = 6 + i * 16;
    const size = buf.readUInt32LE(at + 8);
    const offset = buf.readUInt32LE(at + 12);
    return { width: buf[at] || 256, height: buf[at + 1] || 256, png: buf.subarray(offset, offset + size) };
  });
}

async function expectOpaque(buf: Buffer, label: string) {
  const meta = await sharp(buf).metadata();
  expect(meta.channels, `${label} has an alpha channel`).toBe(3);
  const { data } = await rgba(buf);
  for (let i = 3; i < data.length; i += 4) if (data[i] !== 255) throw new Error(`${label}: pixel ${(i - 3) / 4} is not opaque`);
}

describe("build-og.mjs: Open Graph, stable-URL images and app icons", () => {
  const photo = join(DS, "assets", "Kheelu", "kheelu-on-fur.jpg");

  it("writes exactly the planned files, all outside design-system/ (og.png and logo-mark.png keep their URLs)", () => {
    const paths = IMAGE_OUTPUTS.map((o: { path: string }) => o.path).sort();
    expect(paths).toEqual(
      [
        "public/brand/logo-mark.png",
        "public/media/kheelu-front.jpg",
        "public/og.png",
        "public/og/kheelu.jpg",
        "src/app/apple-icon.png",
        "src/app/favicon.ico",
        "src/app/icon.png",
      ].sort(),
    );
  });

  it.each([
    ["public/og.png", "png"],
    ["public/og/kheelu.jpg", "jpeg"],
  ])("%s is a 1200 x 630 %s card of at most 200 KB (DS 06-surfaces.md:15)", async (path, format) => {
    const buf = read(path);
    const meta = await sharp(buf).metadata();
    expect([meta.format, meta.width, meta.height]).toEqual([format, 1200, 630]);
    expect(buf.length).toBeLessThanOrEqual(200 * KB);
  });

  it.each(["public/og.png", "public/og/kheelu.jpg"])(
    "%s sets the DS photo on its own fur ground, so the card has no seam",
    async (path) => {
      const ground = (await rgba(readFileSync(photo))).data.subarray(0, 3);
      const { data, width } = await rgba(read(path));
      for (const [x, y] of [[4, 4], [4, 620], [1195, 315], [100, 315], [1100, 600]]) {
        const i = (y * width + x) * 4;
        for (let c = 0; c < 3; c++) expect(Math.abs(data[i + c] - ground[c]), `${path} (${x},${y})`).toBeLessThanOrEqual(3);
      }
    },
  );

  it("public/media/kheelu-front.jpg is a square product image for Product JSON-LD", async () => {
    const buf = read("public/media/kheelu-front.jpg");
    const meta = await sharp(buf).metadata();
    expect(meta.format).toBe("jpeg");
    expect(meta.width).toBe(meta.height);
    expect(meta.width).toBeGreaterThanOrEqual(1200);
    expect(buf.length).toBeLessThanOrEqual(200 * KB);
  });

  it("public/brand/logo-mark.png keeps its 512 x 512 size and shows the K on a clear ground", async () => {
    const buf = read("public/brand/logo-mark.png");
    const meta = await sharp(buf).metadata();
    expect([meta.format, meta.width, meta.height]).toEqual(["png", 512, 512]);
    const { data } = await rgba(buf);
    expect(data[3]).toBe(0);
    let inked = 0;
    for (let i = 3; i < data.length; i += 4) if (data[i] === 255) inked++;
    expect(inked / (512 * 512)).toBeGreaterThan(0.1);
  });

  it.each([
    ["src/app/icon.png", 48],
    ["src/app/apple-icon.png", 180],
  ])("%s is an opaque %i px square (lessons §2: the iOS icon must be opaque)", async (path, size) => {
    const buf = read(path);
    const meta = await sharp(buf).metadata();
    expect([meta.format, meta.width, meta.height]).toEqual(["png", size, size]);
    await expectOpaque(buf, path);
  });

  it("src/app/favicon.ico keeps /favicon.ico answering, with opaque 32 and 48 px DS favicons", async () => {
    const entries = icoEntries(read("src/app/favicon.ico"));
    expect(entries.map((e) => [e.width, e.height])).toEqual([[32, 32], [48, 48]]);
    for (const e of entries) {
      const meta = await sharp(e.png).metadata();
      expect([meta.format, meta.width, meta.height]).toEqual(["png", e.width, e.height]);
      await expectOpaque(e.png, `favicon.ico ${e.width}`);
      expect(await exifText(e.png)).toContain(`${HEADER}Logo/favicon-${e.width}.png`);
    }
  });

  it.each([
    ["public/og.png", "Kheelu/kheelu-on-fur.jpg"],
    ["public/og/kheelu.jpg", "Kheelu/kheelu-on-fur.jpg"],
    ["public/media/kheelu-front.jpg", "Kheelu/kheelu-on-fur.jpg"],
    ["public/brand/logo-mark.png", "Logo/kheelona-mark.svg"],
    ["src/app/icon.png", "Logo/favicon-48.png"],
    ["src/app/apple-icon.png", "Logo/apple-touch-icon-180.png"],
  ])("%s carries the generated header naming its DS source", async (path, source) => {
    expect(await exifText(read(path))).toContain(`${HEADER}${source}`);
  });

  it("is up to date: a fresh in-memory render matches every committed image", async () => {
    const fresh = await buildImages();
    expect(fresh.map((o: { path: string }) => o.path).sort()).toEqual(IMAGE_OUTPUTS.map((o: { path: string }) => o.path).sort());
    for (const out of fresh as { path: string; buffer: Buffer }[]) {
      const committed = read(out.path);
      if (out.path.endsWith(".ico")) {
        const [a, b] = [icoEntries(committed), icoEntries(out.buffer)];
        expect(a.length).toBe(b.length);
        for (let i = 0; i < a.length; i++) expect(await meanAbsDiff(a[i].png, b[i].png), out.path).toBeLessThanOrEqual(1);
      } else {
        expect(await meanAbsDiff(committed, out.buffer), out.path).toBeLessThanOrEqual(1);
      }
    }
  }, 30_000);

  it("refuses a photo whose border is not one flat ground (the card would show a seam)", async () => {
    const dir = mkdtempSync(join(tmpdir(), "ks-og-"));
    try {
      for (const sub of ["Kheelu", "Logo"]) {
        const from = join(DS, "assets", sub);
        for (const f of readdirSync(from)) writeFileSync(join(dir, `${sub}--${f}`), readFileSync(join(from, f)));
      }
      const striped = await sharp(photo)
        .composite([{ input: { create: { width: 40, height: 1600, channels: 3, background: { r: 20, g: 20, b: 20 } } }, left: 0, top: 0 }])
        .jpeg()
        .toBuffer();
      const assets = (rel: string) => join(dir, rel.replace("/", "--"));
      writeFileSync(assets("Kheelu/kheelu-on-fur.jpg"), striped);
      await expect(buildImages({ asset: assets })).rejects.toThrow(/kheelu-on-fur\.jpg: border is not one flat ground/);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }, 30_000);
});
