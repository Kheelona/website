import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, utimesSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import postcss, { type AtRule, type Rule } from "postcss";
import { afterAll, describe, expect, it } from "vitest";
import { renderDsTokens, renderTypeSteps } from "../../scripts/assets/build-ds-css.mjs";
import { fontPlan, hasReservedFontName, renderFontsCss, renderPreloads } from "../../scripts/assets/build-fonts.mjs";
import { buildComposeCss, collectComposeFiles, renderComposeCss } from "../../scripts/assets/build-compose-css.mjs";
import { FONT_PRELOADS } from "@/styles/generated/fonts.generated";

/**
 * Generated CSS stays equal to the design system it is derived from (task 1.2, ADR-002, architecture §4.3).
 *
 * design-system/ is read-only, so the site serves derivatives: tokens.css without its font faces, responsive
 * copies of the 19 kh- type classes, subset fonts in public/fonts, and a manifest of the colocated component
 * CSS. Each derivative is re-derived here, independently where the rule is simple enough to restate, and by
 * re-running its script where it is not, so a hand edit or a stale file fails `npm run verify`.
 */

const ROOT = process.cwd();
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");
const TOKENS = read("design-system/project/tokens.css");
const BUNDLE = read("design-system/project/components/bundle.css");
const GENERATED = "src/styles/generated";
const HEADER = /^\/\*[\s\S]*?\*\/\n/;

/** The generated file's body: everything after its leading "GENERATED by ..." comment. */
function body(path: string): string {
  const text = read(path);
  expect(text.startsWith("/* GENERATED by scripts/assets/"), `${path} must start with its GENERATED header`).toBe(true);
  return text.replace(HEADER, "");
}

describe("ds-tokens.css", () => {
  it("is tokens.css minus its four @font-face rules, nothing else changed", () => {
    const lines = TOKENS.split("\n");
    const faces = lines.filter((l) => l.startsWith("@font-face"));
    expect(faces).toHaveLength(4);
    const expected = lines.filter((l) => !l.startsWith("@font-face")).join("\n");
    expect(body(`${GENERATED}/ds-tokens.css`)).toBe(expected);
  });

  it("matches what build-ds-css.mjs writes today (drift)", () => {
    expect(read(`${GENERATED}/ds-tokens.css`)).toBe(renderDsTokens(TOKENS));
  });
});

describe("type-steps.css", () => {
  // The 19 kh- type classes of tokens.css, read with a plain regex so the expectation does not reuse the script.
  const styles = [...TOKENS.matchAll(/^\.kh-([a-z0-9-]+) \{ ([^}]*) \}$/gm)].map((m) => ({ name: m[1], decls: m[2].trim() }));
  const steps: Array<[string, number]> = [["sm", 720], ["lg", 900], ["xl", 1024]];
  const root = postcss.parse(read(`${GENERATED}/type-steps.css`));

  function declsOf(rule: Rule): string {
    return rule.nodes.filter((n) => n.type === "decl").map((d) => `${d.prop}: ${d.value};`).join(" ");
  }

  it("covers the 19 DS type styles", () => {
    expect(styles.map((s) => s.name)).toEqual([
      "display-xl", "display-l", "display-m", "headline", "title", "subtitle", "price", "hand-l", "hand-m", "note",
      "lead", "body-l", "body", "body-s", "label-l", "label", "label-s", "eyebrow", "caption",
    ]);
  });

  it("gives each style a ks-type-<style> class with the DS declarations, at the top level", () => {
    for (const s of styles) {
      const rule = root.nodes.find((n): n is Rule => n.type === "rule" && n.selector === `.ks-type-${s.name}`);
      expect(rule, `.ks-type-${s.name}`).toBeDefined();
      expect(declsOf(rule!)).toBe(s.decls);
    }
  });

  it("gives each style a ks-type-<style>@sm|lg|xl copy inside the DS breakpoint's min-width query", () => {
    for (const [bp, px] of steps) {
      const media = root.nodes.find((n): n is AtRule => n.type === "atrule" && n.name === "media" && n.params === `(min-width: ${px}px)`);
      expect(media, `@media (min-width: ${px}px)`).toBeDefined();
      for (const s of styles) {
        const rule = media!.nodes!.find((n): n is Rule => n.type === "rule" && n.selector === `.ks-type-${s.name}\\@${bp}`);
        expect(rule, `.ks-type-${s.name}\\@${bp}`).toBeDefined();
        expect(declsOf(rule!)).toBe(s.decls);
      }
    }
  });

  it("orders the queries upwards so the wider step wins, and holds nothing else", () => {
    const top = root.nodes.filter((n) => n.type !== "comment");
    expect(top.filter((n) => n.type === "rule")).toHaveLength(19);
    const queries = top.filter((n): n is AtRule => n.type === "atrule").map((n) => n.params);
    expect(queries).toEqual(["(min-width: 720px)", "(min-width: 900px)", "(min-width: 1024px)"]);
    expect(top).toHaveLength(19 + 3);
  });

  it("uses the breakpoint widths bundle.css hard-codes (DS gap G-03)", () => {
    const widths = new Set([...BUNDLE.matchAll(/@media \(min-width: (\d+)px\)/g)].map((m) => Number(m[1])));
    for (const [, px] of steps) expect(widths.has(px), `${px}px in bundle.css`).toBe(true);
  });

  it("matches what build-ds-css.mjs writes today (drift)", () => {
    expect(read(`${GENERATED}/type-steps.css`)).toBe(renderTypeSteps(TOKENS, BUNDLE));
  });
});

describe("fonts", () => {
  const fontsCss = read(`${GENERATED}/fonts.css`);
  const faces = postcss
    .parse(fontsCss)
    .nodes.filter((n): n is AtRule => n.type === "atrule" && n.name === "font-face")
    .map((rule) => {
      const d = Object.fromEntries(rule.nodes!.filter((n) => n.type === "decl").map((n) => [n.prop, n.value]));
      const url = /url\("\/fonts\/([^"]+)"\) format\("woff2"\)/.exec(d.src)?.[1];
      return { family: d["font-family"].replace(/"/g, ""), weight: d["font-weight"], style: d["font-style"], display: d["font-display"], range: d["unicode-range"] ?? "", file: url };
    });
  // The DS faces, read straight from the four @font-face lines of tokens.css.
  const dsFaces = [...TOKENS.matchAll(/^@font-face \{ font-family: "([^"]+)"; src: url\("fonts\/([^"]+)"\) format\("woff2"\); font-weight: ([^;]+); font-style: ([^;]+); font-display: ([^;]+); \}$/gm)].map(
    (m) => ({ family: m[1], file: m[2], weight: m[3], style: m[4], display: m[5] }),
  );
  const publicFonts = readdirSync(join(ROOT, "public/fonts")).filter((f) => !f.startsWith("."));
  const size = (file: string) => statSync(join(ROOT, "public/fonts", file)).size;

  it("reads the four DS faces from tokens.css", () => {
    expect(dsFaces.map((f) => `${f.family} ${f.weight}`)).toEqual(["Baloo 2 400 800", "Nunito 200 1000", "Kalam 400", "Kalam 700"]);
  });

  it("keeps the DS family names, weights and styles, with font-display: swap on every face", () => {
    for (const ds of dsFaces) {
      const mine = faces.filter((f) => f.family === ds.family && f.weight === ds.weight && f.style === ds.style);
      expect(mine.length, `${ds.family} ${ds.weight}`).toBeGreaterThan(0);
    }
    expect(new Set(faces.map((f) => f.family))).toEqual(new Set(dsFaces.map((f) => f.family)));
    for (const f of faces) expect(f.display, `${f.family} ${f.weight}`).toBe("swap");
  });

  it("serves a Latin plus rupee subset for every face, and a Devanagari subset for Baloo 2 only", () => {
    for (const ds of dsFaces) {
      const latin = faces.filter((f) => f.family === ds.family && f.weight === ds.weight && f.range.includes("U+0000-00FF"));
      expect(latin, `${ds.family} ${ds.weight} latin`).toHaveLength(1);
      expect(latin[0].range).toContain("U+20B9");
    }
    const deva = faces.filter((f) => f.range.includes("U+0900-097F"));
    expect(deva.map((f) => f.family)).toEqual(["Baloo 2"]);
    expect(deva[0].range).not.toContain("U+0000-00FF");
  });

  it("points every face at a file in public/fonts, and every file there is used", () => {
    for (const f of faces) expect(f.file && publicFonts.includes(f.file), `${f.family} ${f.weight} -> ${f.file}`).toBe(true);
    expect(new Set(publicFonts)).toEqual(new Set(faces.map((f) => f.file)));
    for (const file of publicFonts) {
      expect(readFileSync(join(ROOT, "public/fonts", file)).subarray(0, 4).toString("latin1"), file).toBe("wOF2");
    }
  });

  it("subsets every face (no DS family declares a Reserved Font Name), so each file is smaller than its source", () => {
    for (const f of faces) {
      const ds = dsFaces.find((d) => d.family === f.family && d.weight === f.weight)!;
      expect(size(f.file!), f.file).toBeLessThan(statSync(join(ROOT, "design-system/project/fonts", ds.file)).size);
    }
  });

  it("recognises an OFL Reserved Font Name notice (the case that must ship a byte-identical copy)", () => {
    expect(hasReservedFontName('Copyright 2011 The Example Project Authors, with Reserved Font Name "Example".')).toBe(true);
    expect(hasReservedFontName("Copyright (c) 2014, Indian Type Foundry (info@indiantypefoundry.com).")).toBe(false);
    expect(hasReservedFontName("Copyright 2019 The Baloo 2 Project Authors (https://github.com/EkType/Baloo2)")).toBe(false);
  });

  it("preloads exactly three Latin files: Nunito, Baloo 2 and the Kalam weight kh-hand uses", () => {
    const handWeight = /\.kh-hand \{[^}]*font-weight: (\d+);/.exec(BUNDLE)?.[1];
    expect(handWeight).toBe("700");
    expect(FONT_PRELOADS.map((p) => `${p.family} ${p.weight}`)).toEqual(["Nunito 200 1000", "Baloo 2 400 800", `Kalam ${handWeight}`]);
    for (const p of FONT_PRELOADS) {
      const face = faces.find((f) => `/fonts/${f.file}` === p.href);
      expect(face, p.href).toBeDefined();
      expect(face!.family).toBe(p.family);
      expect(face!.range).toContain("U+0000-00FF");
      expect(p.type).toBe("font/woff2");
    }
  });

  it("keeps the three preloads within 130 KB together (architecture §10, §12)", () => {
    const total = FONT_PRELOADS.reduce((sum, p) => sum + size(p.href.replace("/fonts/", "")), 0);
    expect(total).toBeLessThanOrEqual(130_000);
  });

  it("matches what build-fonts.mjs writes today: CSS and preload list (drift)", () => {
    const plan = fontPlan(TOKENS);
    expect(fontsCss).toBe(renderFontsCss(plan));
    expect(read(`${GENERATED}/fonts.generated.ts`)).toBe(renderPreloads(plan));
  });

  it("matches what build-fonts.mjs writes today: every font file, byte for byte (drift)", () => {
    // The subsetter's wasm bindings need plain Node typed arrays, which this jsdom test environment replaces, so
    // the byte comparison runs in a child process: `--check` rebuilds in memory and exits 1 on any difference.
    const run = () => execFileSync(process.execPath, [join(ROOT, "scripts/assets/build-fonts.mjs"), "--check"], { cwd: ROOT, stdio: "pipe" }).toString();
    expect(run()).toContain("Font outputs match a fresh build.");
  }, 60_000);
});

describe("compose.css manifest", () => {
  const temps: string[] = [];
  afterAll(() => temps.forEach((t) => rmSync(t, { recursive: true, force: true })));
  function fixture(files: string[]): string {
    const root = mkdtempSync(join(tmpdir(), "ks-compose-"));
    temps.push(root);
    for (const f of files) {
      mkdirSync(dirname(join(root, f)), { recursive: true });
      writeFileSync(join(root, f), "/* fixture */\n");
    }
    return root;
  }
  const imports = (css: string) => [...css.matchAll(/^@import "([^"]+)";$/gm)].map((m) => m[1]);

  it("lists colocated component CSS in the fixed order ui, sections, chrome, layouts, alphabetical within each", () => {
    const root = fixture([
      "src/layouts/LegalTemplate/legal-template.css",
      "src/components/chrome/WhatsAppFloat/whatsapp-float.css",
      "src/components/sections/FilmsStrip/films-strip.css",
      "src/components/sections/store/StoreTop/store-top.css",
      "src/components/ui/Photo/photo.css",
      "src/components/ui/AppScreens/app-screens.css",
      "src/components/atoms/Legacy/legacy.css",
      "src/styles/globals.css",
    ]);
    expect(imports(renderComposeCss(collectComposeFiles(join(root, "src"))))).toEqual([
      "../../components/ui/AppScreens/app-screens.css",
      "../../components/ui/Photo/photo.css",
      "../../components/sections/FilmsStrip/films-strip.css",
      "../../components/sections/store/StoreTop/store-top.css",
      "../../components/chrome/WhatsAppFloat/whatsapp-float.css",
      "../../layouts/LegalTemplate/legal-template.css",
    ]);
  });

  it("allows an empty manifest: a header and no imports", () => {
    const css = renderComposeCss(collectComposeFiles(join(fixture([]), "src")));
    expect(css.startsWith("/* GENERATED by scripts/assets/build-compose-css.mjs")).toBe(true);
    expect(imports(css)).toEqual([]);
    expect(postcss.parse(css).nodes.filter((n) => n.type !== "comment")).toEqual([]);
  });

  // The guards rebuild the manifest while other Vitest workers compile site.css; a reader must never find it half
  // written (task 1.2 review, 2026-10-11), or a compile loses the composition rules.
  it("leaves a current manifest untouched", () => {
    const root = fixture(["src/components/ui/Card/card.css"]);
    const { path } = buildComposeCss({ root });
    const old = new Date("2026-01-01T00:00:00Z");
    utimesSync(path, old, old);
    const before = statSync(path);
    buildComposeCss({ root });
    const after = statSync(path);
    expect(after.mtimeMs).toBe(before.mtimeMs);
    expect(after.ino).toBe(before.ino);
  });

  it("replaces a stale manifest whole: a new file moved into place, never the old one emptied and rewritten", () => {
    const root = fixture(["src/components/ui/Card/card.css"]);
    const { path } = buildComposeCss({ root });
    writeFileSync(path, "/* stale */\n");
    const stale = statSync(path).ino;
    expect(buildComposeCss({ root }).files).toEqual(["components/ui/Card/card.css"]);
    expect(statSync(path).ino).not.toBe(stale);
    expect(imports(readFileSync(path, "utf8"))).toEqual(["../../components/ui/Card/card.css"]);
    expect(readdirSync(dirname(path))).toEqual(["compose.css"]); // no temporary file left behind
  });

  for (const hook of ["predev", "prebuild"]) {
    it(`is written by the ${hook} step file`, () => {
      const root = fixture(["src/components/ui/Card/card.css"]);
      for (const p of [`scripts/steps/${hook}/20-compose-css.mjs`, "scripts/assets/build-compose-css.mjs"]) {
        mkdirSync(dirname(join(root, p)), { recursive: true });
        copyFileSync(join(ROOT, p), join(root, p));
      }
      execFileSync(process.execPath, [join(root, `scripts/steps/${hook}/20-compose-css.mjs`)], { stdio: "pipe" });
      const out = join(root, "src/styles/generated/compose.css");
      expect(existsSync(out)).toBe(true);
      expect(imports(readFileSync(out, "utf8"))).toEqual(["../../components/ui/Card/card.css"]);
    });
  }
});
