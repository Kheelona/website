// Guard for the hero photo's crops (task Q2.1, D064 item 4; assets.md §3).
//
// Home's hero picture is the DS photo library's kabir-02-block-rocket, cut from its 2K master by
// scripts/assets/build-hero-crops.mjs into two committed JPEGs: the 4:5 crop the hero shows from 720 px (the DS photo
// frame's ratio) and the 16:10 crop it shows under 720 px, right under the trust line (D061 item 1's place). Checked
// here: each file's size and ratio, the generated header naming the script and the DS master, drift against a fresh
// in-memory render, pixel by pixel, and the DS cast rule that a crop keeps faces and Kheelu whole and off the edge
// (design-system 03-cast.md, "Using the library"), for the boy, his head and Kheelu. The drift check and the cast rule
// are each proven red here on a planted violation.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { buildHeroCrops } from "../../scripts/assets/build-hero-crops.mjs";
import { cropWindow, HERO_CROPS, HERO_SOURCE, MASTER_SIZE, SUBJECTS, subjectsIn } from "../../scripts/assets/hero-crops.mjs";

const REPO = join(__dirname, "..", "..");
const read = (p: string) => readFileSync(join(REPO, p));
const MASTER = join(REPO, "design-system", "project", "assets", HERO_SOURCE);
const HEADER = "GENERATED by scripts/assets/build-hero-crops.mjs, do not edit; source design-system/project/assets/";

type Box = readonly [number, number, number, number];
type Crop = (typeof HERO_CROPS)[number];

/** Decoded RGB pixels, so two encodes of the same picture compare across platforms. */
async function rgb(buf: Buffer) {
  const { data, info } = await sharp(buf).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
}

/** The largest channel difference anywhere, and the share of pixels whose largest difference exceeds 4 (a mean would
 *  hide a local mark). The bounds are generated-icons.test.ts's for the share cards: room for another platform's JPEG
 *  rounding, none for a visible mark. */
async function drift(a: Buffer, b: Buffer) {
  const [x, y] = await Promise.all([rgb(a), rgb(b)]);
  expect([x.width, x.height]).toEqual([y.width, y.height]);
  let max = 0;
  let over4 = 0;
  for (let i = 0; i < x.data.length; i += 3) {
    const worst = Math.max(Math.abs(x.data[i] - y.data[i]), Math.abs(x.data[i + 1] - y.data[i + 1]), Math.abs(x.data[i + 2] - y.data[i + 2]));
    max = Math.max(max, worst);
    if (worst > 4) over4++;
  }
  return { max, fracOver4: over4 / (x.width * x.height) };
}
const DRIFT = { max: 16, fracOver4: 0.0005 };
const withinDrift = (d: { max: number; fracOver4: number }) => d.max <= DRIFT.max && d.fracOver4 <= DRIFT.fracOver4;

/** The text of the EXIF ImageDescription (IFD0 tag 0x010e), read from the raw EXIF block. */
async function exifText(buf: Buffer) {
  const { exif } = await sharp(buf).metadata();
  return exif ? exif.toString("latin1") : "";
}

/** A box lies inside the crop with at least `margin` (a share of the crop) on every side. */
const insideWith = (box: Box, margin: number) => box[0] >= margin && box[1] >= margin && box[2] <= 1 - margin && box[3] <= 1 - margin;
/** The DS rule's "off the edge", as a share of the crop: at least 1 % clear on every side. */
const OFF_THE_EDGE = 0.01;

describe("the hero photo's crops (task Q2.1, D064 item 4)", () => {
  it("cuts two crops of the DS photo library's kabir-02-block-rocket master: 4:5 at 1200 x 1500 and 16:10 at 1600 x 1000", async () => {
    expect(HERO_SOURCE).toBe("Photo library/kabir-02-block-rocket.jpg");
    const { width, height } = await sharp(MASTER).metadata();
    expect([width, height]).toEqual([MASTER_SIZE.width, MASTER_SIZE.height]);
    expect(HERO_CROPS.map((c: Crop) => [c.path, c.width, c.height])).toEqual([
      ["src/assets/hero/kabir-02-block-rocket-4x5.jpg", 1200, 1500],
      ["src/assets/hero/kabir-02-block-rocket-16x10.jpg", 1600, 1000],
    ]);
    for (const crop of HERO_CROPS as Crop[]) {
      const meta = await sharp(read(crop.path)).metadata();
      expect([meta.format, meta.width, meta.height], crop.path).toEqual(["jpeg", crop.width, crop.height]);
      // The window it is cut from has the crop's own ratio, within a master pixel, and lies inside the master.
      const w = cropWindow(crop, MASTER_SIZE);
      expect(Math.abs(w.width / w.height - crop.width / crop.height), crop.path).toBeLessThan(1 / w.height);
      expect(w.left >= 0 && w.top >= 0 && w.left + w.width <= MASTER_SIZE.width && w.top + w.height <= MASTER_SIZE.height, crop.path).toBe(true);
    }
  });

  it.each(HERO_CROPS.map((c: Crop) => [c.path]))("%s carries the generated header naming the script and its DS master", async (path) => {
    expect(await exifText(read(path))).toContain(`${HEADER}${HERO_SOURCE}`);
  });

  it("is up to date: a fresh in-memory render matches every committed crop", async () => {
    const fresh = await buildHeroCrops();
    expect(fresh.map((o: { path: string }) => o.path)).toEqual(HERO_CROPS.map((c: Crop) => c.path));
    for (const out of fresh as { path: string; buffer: Buffer }[]) {
      const d = await drift(read(out.path), out.buffer);
      expect(d.max, `${out.path}: largest channel difference`).toBeLessThanOrEqual(DRIFT.max);
      expect(d.fracOver4, `${out.path}: share of pixels off by more than 4`).toBeLessThanOrEqual(DRIFT.fracOver4);
    }
  }, 30_000);

  // Proven red: a mark the size of a short line of text in one corner of a committed crop, under 1 % of it.
  it("flags a text-sized mark added to a committed crop", async () => {
    const committed = read(HERO_CROPS[1].path);
    const strokes = Array.from({ length: 24 }, (_, i) => `<rect x="${i * 16}" y="0" width="4" height="40"/>`).join("");
    const mark = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="400" height="40" fill="#ffffff">${strokes}</svg>`);
    const marked = await sharp(committed).composite([{ input: mark, left: 40, top: 40 }]).jpeg({ quality: 90 }).toBuffer();
    expect(withinDrift(await drift(marked, committed))).toBe(false);
  });

  it.each(HERO_CROPS.map((c: Crop) => [c.path, c]))("%s keeps the boy, his head and Kheelu whole and off the edge (DS 03-cast.md)", (_path, crop) => {
    const kept = subjectsIn(crop as Crop, MASTER_SIZE);
    expect(Object.keys(SUBJECTS).sort()).toEqual(["child", "head", "kheelu"]);
    expect(Object.keys(kept).sort()).toEqual(Object.keys(SUBJECTS).sort());
    for (const [name, box] of Object.entries(kept)) expect(insideWith(box, OFF_THE_EDGE), `${name} ${box.map((v) => v.toFixed(3))}`).toBe(true);
  });

  // Proven red: a window that cuts through Kheelu (the 4:5 crop slid left by a fifth of its width, inside the master).
  it("refuses a crop that cuts a subject: the script throws before it writes anything", async () => {
    const shifted = { ...HERO_CROPS[0], centre: HERO_CROPS[0].centre! - 0.09 };
    const box = subjectsIn(shifted, MASTER_SIZE).kheelu;
    expect(insideWith(box, OFF_THE_EDGE)).toBe(false);
    await expect(buildHeroCrops({ crops: [shifted] })).rejects.toThrow(/kheelu is not whole and off the edge/);
  });
});
