/** photos.ts: key → { alt, wide } (the file imports images, so it is read as text). */
function photoTable() {
  const text = readSrc("src/content/en-IN/stories/photos.ts");
  const body = text.slice(text.indexOf("export const photos"));
  const table = {};
  for (const m of body.matchAll(/^ {2}"([a-z0-9-]+)": \{([\s\S]*?)^ {2}\},?$/gm)) {
    const alt = /alt:\s*"((?:[^"\\]|\\.)*)"/.exec(m[2]);
    if (!alt) throw new Error(`photos.ts: no alt for "${m[1]}"`);
    table[m[1]] = { alt: JSON.parse(`"${alt[1]}"`), wide: /wide:\s*true/.test(m[2]) };
  }
  if (Object.keys(table).length === 0) throw new Error("photos.ts: no photos found");
  return table;
}

/** hub.ts: the hub's curation, per topic its featured guide and listed order. */
function hubCuration() {
  const text = readSrc("src/content/en-IN/stories/hub.ts");
  const start = text.indexOf("export const hubTopics");
  const block = text.slice(start, text.indexOf("\n];", start));
  return [...block.matchAll(/\{\s*topic:\s*"([^"]+)",([\s\S]*?)\n {2}\}/g)].map((m) => ({
    topic: m[1],
    featured: /featured:\s*"([^"]+)"/.exec(m[2])?.[1],
    slugs: [.../slugs:\s*\[([\s\S]*?)\]/.exec(m[2])?.[1].matchAll(/"([^"]+)"/g) ?? []].map((s) => s[1]),
  }));
}

