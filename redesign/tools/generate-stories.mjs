async function loadPosts(args) {
  if (args.api) {
    const url = `${(process.env.BLOG_API_URL || JOURNAL_API).replace(/\/+$/, "")}${JOURNAL_POSTS_PATH}`;
    let last;
    for (let i = 0; i < 3; i++) {
      try {
        const res = await fetch(url, { headers: { accept: "application/json" }, signal: AbortSignal.timeout(20_000) });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        return { posts: (await res.json())?.data?.posts, from: url };
      } catch (e) { last = e; await new Promise((r) => setTimeout(r, 2000 * (i + 1))); }
    }
    throw new Error(`could not reach ${url} (${last?.message ?? last})`);
  }
  const file = args.snapshot ?? join(SITE, JOURNAL_SNAPSHOT);
  return { posts: JSON.parse(readFileSync(file, "utf8")).posts, from: file };
}

export async function run(argv) {
  const args = { api: argv.includes("--api"), check: argv.includes("--check"), snapshot: argv.includes("--snapshot") ? argv[argv.indexOf("--snapshot") + 1] : undefined };
  const { posts: raw, from } = await loadPosts(args);
  const drafts = Array.isArray(raw) ? raw.filter((p) => p && ((p.status !== undefined && p.status !== "published") || p.draft === true)) : [];
  for (const d of drafts) console.log(`stories: skipping draft "${d.slug}"`);
  const posts = Array.isArray(raw) ? raw.filter((p) => !drafts.includes(p)).map(({ status, draft, ...p }) => p) : raw;
  const rules = { themes: topics.map((t) => t.title), imagesBase: JOURNAL_IMAGES, findBanned };
  const problems = validatePosts(posts, rules);
  const count = Array.isArray(posts) ? countProblem(posts.length) : null;
  if (problems.length || count) throw new Error(`the posts from ${from} would not pass the journal gate, so nothing was written:\n  ${[...problems, ...(count ? [count] : [])].join("\n  ")}`);
  const warnings = [];
  const warn = (m) => warnings.push(m);
  for (const m of editorialWarnings(posts, rules)) warn(m);

  const redirected = redirectedSlugs();
  const kept = posts.filter((p) => {
    if (redirected.has(p.slug)) { warn(`post "${p.slug}": its address is a redirect's source, so it is left out; unpublish it (rule 17)`); return false; }
    return true;
  });
  const published = new Set(kept.map((p) => p.slug));
  const offers = ringOffers(readingOrder(kept, topics.map((t) => t.title)));
  const refusals = [];
  const articles = [];
  kept.forEach((p, n) => {
    try { articles.push(adapt(p, published, offers.get(p.slug), n, warn)); } catch (e) { if (e instanceof Refusal) refusals.push(e.message); else throw e; }
  });
  if (refusals.length) throw new Error(`the journal is refused, so nothing was written:\n  ${refusals.join("\n  ")}`);
  const bySlug = new Map(articles.map((a) => [a.slug, a]));
  const groups = hubGroups(articles, warn);

  const files = new Map([[join(ROOT, "pages/stories.html"), hubPage(articles, groups)]]);
  for (const a of articles) files.set(join(ROOT, "pages/stories", `${a.slug}.html`), articlePage(a, bySlug));
  for (const w of warnings) console.log(`stories: warning: ${w}`);
  if (args.check) return console.log(`stories --check: ${articles.length} posts from ${from} render; nothing written`);

  /* Write, then remove what the generator owns and no longer makes (a post unpublished in the dashboard). */
  mkdirSync(join(ROOT, "pages/stories"), { recursive: true });
  for (const [path, html] of files) writeFileSync(path, html);
  const owned = (p) => existsSync(p) && /GENERATED by tools\/generate-stories\.mjs|by tools\/import-stories\.py/.test(readFileSync(p, "utf8"));
  const removed = [];
  for (const f of readdirSync(join(ROOT, "pages/stories"))) {
    const slug = f.replace(/\.html$/, "");
    if (f.endsWith(".html") && !bySlug.has(slug) && owned(join(ROOT, "pages/stories", f))) { rmSync(join(ROOT, "pages/stories", f)); removed.push(slug); }
  }
  if (existsSync(join(ROOT, "stories"))) {
    for (const d of readdirSync(join(ROOT, "stories"), { withFileTypes: true })) {
      if (d.isDirectory() && !bySlug.has(d.name) && owned(join(ROOT, "stories", d.name, "index.html"))) { rmSync(join(ROOT, "stories", d.name), { recursive: true }); removed.push(`${d.name} (built)`); }
    }
  }
  console.log(`stories: ${articles.length} posts from ${from} → pages/stories.html + ${articles.length} guides${removed.length ? `; removed ${removed.join(", ")}` : ""}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try { await run(process.argv.slice(2)); } catch (e) { console.error(`stories: FAILED: ${e.message}`); process.exitCode = 1; }
}
