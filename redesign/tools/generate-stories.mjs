/** Rich text (after nowrapAges) as HTML: {nowrap:…}, {hand:…} (a .mark), {price:…}, {delivery}, [^n]; Khelu. */
function fmt(text, ctx) {
  const re = /\{nowrap:([^{}]*)\}|\{hand:([^{}]*)\}|\{price:([a-z]+)\}|\{delivery\}|\[\^(\d+)\]/g;
  let out = "", from = 0;
  for (const m of text.matchAll(re)) {
    out += esc(khelu(text.slice(from, m.index)));
    if (m[1] !== undefined) out += `<span class="nowrap">${esc(khelu(m[1]))}</span>`;
    else if (m[2] !== undefined) out += `<span class="mark mark--${ctx.mark()}">${fmt(m[2], ctx)}</span>`;
    else if (m[3] !== undefined) {
      if (!(m[3] in PRICES)) throw new Error(`unknown price token {price:${m[3]}}`);
      out += PRICES[m[3]];
    } else if (m[4] !== undefined) out += `<a class="cite" href="#src-${m[4]}" aria-label="Source ${m[4]}">[${m[4]}]</a>`;
    else out += esc(DELIVERY);
    from = m.index + m[0].length;
  }
  return out + esc(khelu(text.slice(from)));
}
