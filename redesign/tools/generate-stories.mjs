const slugify = (s, used) => {
  let base = s.toLowerCase().replace(/[’']/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60).replace(/-$/, "") || "part";
  let out = base;
  for (let i = 2; used.has(out); i++) out = `${base}-${i}`;
  used.add(out);
  return out;
};
