const PITCH_PATH = /^\/(products|store)(\/|$|[?#])/;
const isPitchLink = (href) => {
  if (PITCH_PATH.test(href)) return true;
  if (!/^https:\/\//i.test(href)) return false;
  try {
    const u = new URL(href), h = u.hostname.toLowerCase();
    if (["store.kheelona.com", "betastore.kheelona.com"].includes(h)) return true;
    return ["kheelona.com", "www.kheelona.com", "betawebsite.kheelona.com"].includes(h) && PITCH_PATH.test(u.pathname);
  } catch { return false; }
};

/* ── the post body (to-article.ts §5.1, ported) ───────────────────────────────────────────────────────── */
const MARKS = new Set(["bold", "link"]);
const isBold = (n) => n.type === "text" && (n.marks ?? []).some((m) => m.type === "bold");
const linkOf = (n) => (n.marks ?? []).find((m) => m.type === "link")?.attrs.href;

function richText(w, nodes) {
  let out = "";
  for (let i = 0; i < nodes.length; ) {
    const n = nodes[i];
    if (n.type === "hardBreak") { out += " "; i++; continue; }
    if (n.type !== "text") fail(w.slug, `unknown inline node "${n.type}"`, 3);
    for (const m of n.marks ?? []) if (!MARKS.has(m.type)) fail(w.slug, `unknown mark "${m.type}"`, 3);
    const href = linkOf(n);
    if (href === undefined) { out += fmt(nowrapAges(n.text), w.ctx); i++; continue; }
    if (w.pitchFree && isPitchLink(href)) fail(w.slug, `a guide on the talking topic never links "${href}" (no pitch, B5)`, 18);
    let label = "";
    while (i < nodes.length && nodes[i].type === "text" && linkOf(nodes[i]) === href) label += nodes[i++].text;
    const to = /^https:\/\/(beta)?store\.kheelona\.com/i.test(href) ? STORE : href;
    const a = `<a href="${attr(to)}">${fmt(nowrapAges(label), w.ctx)}</a>`;
    out += href.startsWith("tel:") ? `<span class="nowrap">${a}</span>` : a;
  }
  return out;
}
const lines = (content) => {
  const runs = [[]];
  for (const n of content) n.type === "hardBreak" ? runs.push([]) : runs[runs.length - 1].push(n);
  return runs.filter((r) => r.some((n) => n.type === "text" && n.text.trim() !== ""));
};
const LEAD_PUNCT = /^[:;,.!?)]+/;
function leadOf(w, run, where) {
  const texts = run.filter((n) => n.type === "text");
  const all = texts.length > 0 && texts.every(isBold);
  if (all) return { text: richText(w, run).trim(), all };
  let k = 0;
  while (k < run.length && isBold(run[k])) k++;
  if (run.slice(k).some(isBold)) w.warn(`${where}: bold inside a line shows as plain text (§5.2)`);
  let lead = k > 0 ? richText(w, run.slice(0, k)).trimEnd() : undefined;
  let text = richText(w, run.slice(k)).trimStart();
  const p = lead === undefined ? undefined : LEAD_PUNCT.exec(text)?.[0];
  if (p !== undefined) { lead += p; text = text.slice(p.length).trimStart(); }
  return { lead, text: text === "" ? undefined : text, all };
}
const withLead = ({ lead, text }) => (lead !== undefined ? `<strong>${lead}</strong>${text !== undefined ? ` ${text}` : ""}` : text ?? "");
const noBreaks = (content) => (content ?? []).map((n) => (n.type === "hardBreak" ? { type: "text", text: " " } : n));
const icon = (w, name, where) => {
  if (name === undefined || name === null) return undefined;
  if (!(name in ICON_PATHS)) fail(w.slug, `${where}: icon "${name}" is not a DS icon`, 12);
  return name;
};

function paragraphs(w, node, where) {
  return lines(node.content ?? []).map((run) => {
    const l = leadOf(w, run, where);
    return l.all ? `<p class="pull">${l.text}</p>` : `<p>${withLead(l)}</p>`;
  });
}
function list(w, node, where) {
  const style = node.type === "orderedList" ? "steps" : node.attrs?.style ?? "bullets";
  if (!["bullets", "checks", "tips", "facts", "steps"].includes(style)) fail(w.slug, `${where}: unknown list style "${style}"`, 3);
  const items = node.content.map((item, i) => {
    if (item.type !== "listItem") fail(w.slug, `${where}: unknown list node "${item.type}"`, 3);
    const at = `${where}.content[${i}]`;
    const l = leadOf(w, noBreaks(item.content?.[0]?.content), at);
    const line = l.all ? `<strong>${l.text}</strong>` : withLead(l);
    const name = icon(w, item.attrs?.icon, at);
    if ((style === "tips" || style === "facts") && name === undefined) fail(w.slug, `${at}: a ${style === "tips" ? "tip" : "fact"} needs an icon`, 12);
    return { line, name };
  });
  if (style === "facts") return { kind: "facts", html: items.map((it) => `<li><span class="facts__ico">${svg(it.name, "ico-svg")}</span><p>${it.line}</p></li>`).join("") };
  if (style === "tips") return { kind: "list", html: `<ul class="tips">${items.map((it) => `<li><span class="tips__ico">${svg(it.name, "ico-svg")}</span><span>${it.line}</span></li>`).join("")}</ul>` };
  if (style === "checks") return { kind: "list", html: `<ul class="checks">${items.map((it) => `<li>${it.line}</li>`).join("")}</ul>` };
  const tag = style === "steps" ? "ol" : "ul";
  return { kind: "list", html: `<${tag}>${items.map((it) => `<li>${it.name ? `${svg(it.name, "li-ico")} ` : ""}${it.line}</li>`).join("")}</${tag}>` };
}
function quote(w, node, where) {
  const style = node.attrs?.style ?? "callout";
  if (style === "callout") {
    const name = icon(w, node.attrs?.icon, where);
    if (name === undefined) fail(w.slug, `${where}: a callout needs an icon`, 12);
    const para = node.content[0];
    const l = leadOf(w, noBreaks(para?.content), where);
    return `<div class="try"><span class="try__ico">${svg(name, "ico-svg")}</span><p>${l.all ? `<strong>${l.text}</strong>` : withLead(l)}</p></div>`;
  }
  if (style !== "questions") fail(w.slug, `${where}: unknown quote style "${style}"`, 3);
  icon(w, node.attrs?.icon, where);
  let out = "";
  node.content.forEach((child, i) => {
    const at = `${where}.content[${i}]`;
    if (child.type === "heading") out += `<h3>${richText(w, child.content ?? []).trim()}</h3>`;
    else if (child.type === "paragraph") out += lines(child.content ?? []).map((run) => `<p>${richText(w, run).trim()}</p>`).join("");
    else fail(w.slug, `${at}: unknown node "${child.type}" in a questions block`, 3);
  });
  return `<div class="asks">${out}</div>`;
}
/** An image node → { html, image } (a DS photo by key, or an upload at its public API address). */
function figure(w, node, where, cls = "fig") {
  const { photo: key, caption = "", src, width, height, alt } = node.attrs;
  const cap = caption.trim() ? `<figcaption>${fmt(nowrapAges(caption.trim()), w.ctx)}</figcaption>` : "";
  const image = imageRef(w, key, src, width, height, alt, where);
  return { image, html: `<figure class="${cls} ${cls}--${image.shape}">${imgTag(image, "(min-width: 1000px) 46rem, 100vw")}${cap}</figure>` };
}
function imageRef(w, key, src, width, height, alt, where) {
  if (key) {
    const entry = PHOTOS[key] ?? fail(w.slug, `${where}: photo "${key}" is not in the photo table (src/content/en-IN/stories/photos.ts)`, 12);
    if (TOY_CLOSEUP_KEYS.has(key)) return { ...TUMMY, alt: khelu(entry.alt), shape: "square", key };
    if (!existsSync(join(ROOT, "assets/img/stories", `${key}.webp`))) {
      throw new Error(`photo "${key}" has no web copy: add assets/img/stories/${key}.webp and ${key}-640.webp (cwebp -q 78, ≤1200 wide)`);
    }
    const small = existsSync(join(ROOT, "assets/img/stories", `${key}-640.webp`));
    const [width, height] = webpSize(join(ROOT, "assets/img/stories", `${key}.webp`));
    return {
      src: `/assets/img/stories/${key}.webp`, ...(small && { srcset: `/assets/img/stories/${key}-640.webp 640w, /assets/img/stories/${key}.webp ${width}w` }),
      width, height, alt: khelu(entry.alt), shape: entry.wide ? "wide" : "tall", key,
    };
  }
  if (!src || !src.startsWith(JOURNAL_IMAGES) || !width || !height) fail(w.slug, `${where}: the image "${src}" is not an upload under ${JOURNAL_IMAGES} with its size`, 13);
  /* Never a photo of the old toy as a product shot: an upload described as the toy up close becomes the current toy. */
  if (/\b(kheelu|khelu)\b/i.test(alt) && /\b(up close|close-up|closeup|tummy unit|belly)\b/i.test(alt)) {
    w.warn(`${where}: "${alt}" reads as a close-up of the toy; shown as the current toy's tummy (khelu-tummy-800.webp)`);
    return { ...TUMMY, alt: khelu(alt), shape: "square" };
  }
  return { src, width, height, alt: khelu(alt), shape: width / height >= 1.6 ? "wide" : width === height ? "square" : "tall", upload: true };
}
/** A WebP file's pixel size, from its header (VP8, VP8L or VP8X). */
function webpSize(path) {
  const b = readFileSync(path);
  const kind = b.toString("ascii", 12, 16);
  if (kind === "VP8X") return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
  if (kind === "VP8 ") return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  if (kind === "VP8L") { const n = b.readUInt32LE(21); return [1 + (n & 0x3fff), 1 + ((n >> 14) & 0x3fff)]; }
  throw new Error(`${path} is not a WebP image`);
}
function imgTag(img, sizes, { eager = false, alt } = {}) {
  const set = img.srcset ? ` srcset="${img.srcset}" sizes="${sizes}"` : "";
  const load = eager ? ' fetchpriority="high"' : ' loading="lazy" decoding="async"';
  return `<img src="${attr(img.src)}"${set} width="${img.width}" height="${img.height}"${load} alt="${attr(alt ?? img.alt)}">`;
}

function block(w, node, where) {
  switch (node.type) {
    case "paragraph": return paragraphs(w, node, where);
    case "heading": return [`<h3>${richText(w, node.content ?? []).trim()}</h3>`];
    case "bulletList": case "orderedList": {
      const l = list(w, node, where);
      return [l.kind === "facts" ? { facts: l.html } : l.html];
    }
    case "blockquote": return [quote(w, node, where)];
    case "image": return [figure(w, node, where).html];
    case "videoEmbed": return [video(w, node, where)];
    case "horizontalRule": return [];
    default: fail(w.slug, `${where}: unknown block "${node.type}"; the generator renders every block the dashboard can produce, and no other`, 3);
  }
}
function video(w, node, where) {
  const { provider, videoId, title, caption = "" } = node.attrs;
  const src = provider === "youtube" ? `https://www.youtube-nocookie.com/embed/${encodeURIComponent(videoId)}?autoplay=1&rel=0`
    : provider === "vimeo" ? `https://player.vimeo.com/video/${encodeURIComponent(videoId)}?autoplay=1&dnt=1`
    : fail(w.slug, `${where}: unknown video provider "${provider}"`, 6);
  const still = provider === "youtube" ? `<img src="https://i.ytimg.com/vi/${attr(videoId)}/hqdefault.jpg" width="480" height="360" loading="lazy" decoding="async" alt="">` : "";
  const cap = caption.trim() ? `<figcaption>${fmt(nowrapAges(caption.trim()), w.ctx)}</figcaption>` : "";
  return `<figure class="video"><button type="button" class="video__play" data-video-src="${attr(src)}" aria-label="${attr(`${COPY.videoLabel} ${khelu(title)}`)}">${still}<span class="video__btn" aria-hidden="true">${svg("play", "ico-svg")}</span><span class="video__title">${esc(khelu(title))}</span></button>${cap}</figure>`;
}
/** Nodes as HTML, joining a DS photo that follows a facts list into the facts card (§5.1). */
function blocks(w, nodes) {
  const out = [];
  nodes.forEach(({ node, where }) => {
    const prev = out[out.length - 1];
    if (node.type === "image" && node.attrs.photo && prev && typeof prev === "object" && prev.facts !== undefined && prev.figure === undefined) {
      if ((node.attrs.caption ?? "").trim()) w.warn(`${where}: a facts list's photo shows no caption; "${node.attrs.caption.trim()}" is left out (§5.1)`);
      prev.figure = figure(w, node, where, "facts__fig").html.replace(/<figcaption>.*?<\/figcaption>/, "");
      return;
    }
    out.push(...block(w, node, where));
  });
  return out.map((b) => (typeof b === "string" ? b : `<div class="facts"><ul class="facts__list">${b.facts}</ul>${b.figure ?? ""}</div>`));
}
const isH2 = (n) => n?.type === "heading" && n.attrs?.level === 2;
const isFacts = (n) => n?.type === "bulletList" && n.attrs?.style === "facts";

function body(w, post) {
  const nodes = post.body.content.map((node, i) => ({ node, where: `body[${i}]` }));
  const firstH2 = nodes.findIndex(({ node }) => isH2(node));
  const rule = nodes.findIndex(({ node }) => node.type === "horizontalRule");
  const split = post.answer && rule !== -1 && (firstH2 === -1 || rule < firstH2) ? rule : -1;
  const detailNodes = nodes.slice(0, split + 1).filter(({ node }) => node.type !== "horizontalRule");
  for (const { node, where } of detailNodes) if (node.type === "videoEmbed" || node.type === "image") fail(w.slug, `${where}: the answer card holds text only; put it after the rule`, 4);
  const detail = blocks(w, detailNodes);
  const parts = [];
  let part = null;
  const close = () => {
    if (!part) return;
    const html = blocks(w, part.nodes);
    if (part.title !== undefined || html.length) parts.push({ ...part, html, breakout: part.nodes.some(({ node }) => isFacts(node)) });
    part = null;
  };
  const rest = nodes.slice(split + 1);
  rest.forEach((entry, i) => {
    const { node, where } = entry;
    const between = node.type === "image" && isH2(rest[i + 1]?.node) && !(node.attrs.photo && isFacts(rest[i - 1]?.node));
    if (isH2(node)) {
      close();
      const title = richText(w, node.content ?? []).trim();
      const words = plain((node.content ?? []).map((n) => n.text ?? " ").join("")).trim();
      part = { title, words, anchor: node.attrs.anchor ?? undefined, nodes: [] };
    } else if (node.type === "heading" && node.attrs?.level !== 3) fail(w.slug, `${where}: heading level ${node.attrs?.level}`, 3);
    else if (node.type === "horizontalRule") { close(); part = { nodes: [] }; }
    else if (between) { close(); parts.push({ figure: figure(w, node, where).html }); }
    else { part ??= { nodes: [] }; part.nodes.push(entry); }
  });
  close();
  if (post.ageNote) {
    const note = `<p class="disclaimer">${fmt(nowrapAges(post.ageNote), w.ctx)}</p>`;
    const last = parts[parts.length - 1];
    if (last && !last.figure) last.html.push(note);
    else parts.push({ nodes: [], html: [note] });
  }
  return { detail, parts };
}

/* ── one post → an article ───────────────────────────────────────────────────────────────────────────── */
function adapt(post, published, offers, n, warn) {
  const topic = topics.find((t) => t.title === post.theme) ?? fail(post.slug, `theme "${post.theme}" is not a topic title`, 10);
  const marks = TINTS.slice(n % 6).concat(TINTS.slice(0, n % 6));
  const ctx = { marks, mark() { const m = this.marks.shift(); this.marks.push(m); return m; } };
  const w = { slug: post.slug, ctx, pitchFree: topic.close === "keep", warn: (m) => warn(`post "${post.slug}": ${m}`) };
  const person = PEOPLE.find((p) => p.name === post.author);
  if (!person && post.author !== TEAM.author) fail(post.slug, `the byline "${post.author}" is not one the site lists (${[TEAM.author, ...PEOPLE.map((p) => p.name)].join(", ")})`, 11);
  let image;
  if (post.photo) {
    const entry = PHOTOS[post.photo] ?? fail(post.slug, `photo "${post.photo}" is not in the photo table`, 12);
    if (TOY_CLOSEUP_KEYS.has(post.photo)) fail(post.slug, `photo "${post.photo}" cannot head a guide`, 12);
    image = imageRef(w, post.photo, null, null, null, entry.alt, "photo");
    image.card = `${SITE_URL}/og/${post.photo}.jpg`;
  } else if (post.hero) {
    image = imageRef(w, null, post.hero, post.heroWidth, post.heroHeight, post.heroAlt, "hero");
    image.card = post.hero;
  } else if (w.pitchFree) fail(post.slug, "a guide on the talking topic needs a head photo or a cover (P19)", 18);
  if (topic.disclaimer !== undefined && !post.answer) fail(post.slug, "a guide on the talking topic needs its answer card", 18);
  const { detail, parts } = body(w, post);
  const { related, filled } = fillRelated(post.slug, post.related ?? [], published, offers ?? []);
  if (filled.length) w.warn(`related filled from the ring: ${filled.join(", ")} (rule 19)`);
  let h1 = post.title;
  if (post.accent) {
    const at = post.title.indexOf(post.accent);
    if (at === -1 || post.title.indexOf(post.accent, at + 1) !== -1) w.warn(`the accent "${post.accent}" is not in the title once; the h1 shows no accent (rule 23)`);
    else h1 = `${nowrapAges(post.title.slice(0, at))}{hand:${nowrapAges(post.accent)}}${nowrapAges(post.title.slice(at + post.accent.length))}`;
  } else h1 = nowrapAges(h1);
  const metaTitle = post.metaTitle ?? (`${post.title} · Kheelona`.length <= 60 ? `${post.title} · Kheelona` : post.title);
  return {
    post, topic, w, ctx, image, detail, parts, related, person, n,
    slug: post.slug, h1, metaTitle,
    card: { title: post.cardTitle ?? post.title, summary: post.summary ?? post.lead ?? post.description },
    minutes: readMinutes(post),
  };
}

