/** hub.ts's curation over the published articles (to-article.ts hubGroups, ported). */
function hubGroups(articles, warn) {
  const bySlug = new Map(articles.map((a) => [a.slug, a]));
  const curation = hubCuration();
  return topics.map((t) => {
    const o = curation.find((c) => c.topic === t.id) ?? { slugs: [] };
    let featured = o.featured;
    if (featured && (!bySlug.has(featured) || bySlug.get(featured).topic.id !== t.id || !bySlug.get(featured).image)) {
      warn(`hub: the featured "${featured}" is not a published ${t.id} guide with a photo; skipped (rule 25)`);
      featured = undefined;
    }
    const listed = o.slugs.filter((s) => {
      const ok = bySlug.has(s) && bySlug.get(s).topic.id === t.id;
      if (!ok) warn(`hub: "${s}" is not a published ${t.id} guide; skipped (rule 25)`);
      return ok;
    });
    const named = new Set([...listed, ...(featured ? [featured] : [])]);
    const others = articles.filter((a) => a.topic.id === t.id && !named.has(a.slug))
      .sort((x, y) => y.post.published.localeCompare(x.post.published) || x.slug.localeCompare(y.slug)).map((a) => a.slug);
    const slugs = [...listed, ...others];
    if (!featured && !slugs.length) warn(`hub: the topic "${t.id}" has no guide (rule 25)`);
    return { topic: t.id, featured, slugs };
  });
}

